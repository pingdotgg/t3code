// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - a dev script over plain files, like workflow-link.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import { listWorkflowSkills } from "./workflow-link.ts";

export interface SkillMap {
  /** skill → the skills its files mention, sorted. */
  readonly calls: ReadonlyMap<string, ReadonlyArray<string>>;
  readonly group: ReadonlyMap<string, string>;
  readonly userOnly: ReadonlySet<string>;
}

const MAP_FILE = "skill-map.md";

function readSkillText(dir: string): string {
  return NodeFS.readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md") && entry.name !== MAP_FILE)
    .map((entry) => NodeFS.readFileSync(NodePath.join(entry.parentPath, entry.name), "utf8"))
    .join("\n");
}

/**
 * A mention is a skill name set off as a name: in backticks, quotes or bold, or as a path segment.
 * Plain prose never counts, so skills named like common words ("how", "teach") stay unambiguous.
 */
export function buildSkillMap(skillsRoot: string): SkillMap {
  const skills = listWorkflowSkills(skillsRoot);
  const names = [...skills.keys()];
  const calls = new Map<string, string[]>();
  const group = new Map<string, string>();
  const userOnly = new Set<string>();
  for (const [name, dir] of skills) {
    group.set(name, NodePath.relative(skillsRoot, dir).split(NodePath.sep)[0] ?? "");
    const text = readSkillText(dir);
    if (/^disable-model-invocation:\s*true/m.test(text)) userOnly.add(name);
    const mentioned = names.filter((other) => {
      if (other === name) return false;
      const escaped = other.replaceAll("-", "\\-");
      return new RegExp(`[\`"*/]${escaped}(?:[\`"*/]|\\s+skill)`).test(text);
    });
    calls.set(name, mentioned.toSorted());
  }
  return { calls, group, userOnly };
}

export function renderSkillMap(map: SkillMap): string {
  const calledBy = new Map<string, number>();
  for (const callees of map.calls.values())
    for (const callee of callees) calledBy.set(callee, (calledBy.get(callee) ?? 0) + 1);
  const names = [...map.calls.keys()].toSorted();
  const callsOut = (name: string) => (map.calls.get(name)?.length ?? 0) > 0;
  const isCalled = (name: string) => (calledBy.get(name) ?? 0) > 0;
  const tag = (name: string) => (map.userOnly.has(name) ? `${name} (user-only)` : name);
  const list = (filter: (name: string) => boolean) =>
    names.filter(filter).map(tag).join(", ") || "none";

  // The principles all hang off the same few skills; one node keeps the chart readable.
  const node = (name: string) => (name.startsWith("principle-") ? "principle-leaves" : name);
  const id = (name: string) => node(name).replaceAll("-", "_");
  const groups = [...new Set(map.group.values())].toSorted();
  const mermaid = ["flowchart LR"];
  for (const g of groups) {
    mermaid.push(`  subgraph ${g}`);
    for (const name of names.filter(
      (n) => map.group.get(n) === g && !n.startsWith("principle-") && (callsOut(n) || isCalled(n)),
    ))
      mermaid.push(`    ${id(name)}["${tag(name)}"]`);
    if (names.some((n) => map.group.get(n) === g && n.startsWith("principle-")))
      mermaid.push(`    principle_leaves["principle-* (see lists above)"]`);
    mermaid.push("  end");
  }
  const edges = new Set<string>();
  for (const name of names)
    for (const callee of map.calls.get(name) ?? [])
      if (node(name) !== node(callee)) edges.add(`  ${id(name)} --> ${id(callee)}`);
  mermaid.push(...edges);

  return [
    "# Skill map",
    "",
    "Generated by `vp run workflow:map` from every `workflow/skills/*/*/**.md`. Do not edit by hand.",
    "An arrow means the first skill's files name the second, so it may hand work to it or tell the agent to read it.",
    "",
    `- **Entry points** (call others, nothing calls them): ${list((n) => callsOut(n) && !isCalled(n))}`,
    `- **Hubs** (call others and are called): ${list((n) => callsOut(n) && isCalled(n))}`,
    `- **Leaves** (called, call nothing): ${list((n) => !callsOut(n) && isCalled(n))}`,
    `- **Standalone** (no links either way): ${list((n) => !callsOut(n) && !isCalled(n))}`,
    "",
    "```mermaid",
    ...mermaid,
    "```",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const root = NodePath.resolve(import.meta.dirname, "..", "workflow", "skills");
  const out = NodePath.join(root, "ak", "ak-help", MAP_FILE);
  NodeFS.writeFileSync(out, renderSkillMap(buildSkillMap(root)));
  console.log(`workflow-map: wrote ${NodePath.relative(process.cwd(), out)}`);
}
