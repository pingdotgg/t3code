#!/usr/bin/env node
// Bundles the editor bridge plugins in integrations/game-bridges into a server module, so the
// server can install them into projects in dev and in packaged builds alike.
// Usage: node scripts/generate-game-bridge-assets.ts [--check]
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeProcess from "node:process";
import * as NodeURL from "node:url";

const root = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "..");
const source = NodePath.join(root, "integrations", "game-bridges");
const output = NodePath.join(root, "apps", "server", "src", "gameDev", "bridgeAssets.generated.ts");
const groups = { roblox: "roblox", unity: "unity/com.continuum.bridge", unreal: "unreal/ContinuumBridge", blender: "blender" } as const;

function walk(directory: string): string[] {
  return NodeFS.readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const full = NodePath.join(directory, entry.name);
      if (entry.isDirectory()) return walk(full);
      return /\.(lua|cs|asmdef|json|uplugin|py)$/.test(entry.name) ? [full] : [];
    })
    .sort();
}

let text = "// Generated by scripts/generate-game-bridge-assets.ts from integrations/game-bridges. Do not edit.\n";
text += "export const GAME_BRIDGE_FILES = {\n";
for (const [name, folder] of Object.entries(groups)) {
  const base = NodePath.join(source, folder);
  text += `  ${name}: [\n`;
  for (const file of walk(base)) {
    const relative = NodePath.relative(base, file).split(NodePath.sep).join("/");
    text += `    { path: ${JSON.stringify(relative)}, contents: ${JSON.stringify(NodeFS.readFileSync(file, "utf8"))} },\n`;
  }
  text += "  ],\n";
}
text += "} as const satisfies Record<string, ReadonlyArray<{ readonly path: string; readonly contents: string }>>;\n";

if (NodeProcess.argv.includes("--check")) {
  const current = NodeFS.existsSync(output) ? NodeFS.readFileSync(output, "utf8") : "";
  if (current !== text) {
    NodeProcess.stderr.write("bridgeAssets.generated.ts is stale; run node scripts/generate-game-bridge-assets.ts\n");
    NodeProcess.exit(1);
  }
} else {
  NodeFS.writeFileSync(output, text);
  NodeProcess.stdout.write(`Wrote ${NodePath.relative(root, output)}\n`);
}
