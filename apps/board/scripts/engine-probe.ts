// Probes the T3 engine behaviors the board depends on, against an isolated engine and the
// operator's Claude Code login. Run: node apps/board/scripts/engine-probe.ts [--checks A,B] [--run-dir DIR] [--findings FILE]
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import { CHECKS, type CheckSpec } from "./probe/checks.ts";
import { claudeProjectKey, claudeProjectsDir } from "./probe/claude.ts";
import {
  connectRpc,
  type ProbeContext,
  reapLeftovers,
  type Rpc,
  startEngine,
} from "./probe/connection.ts";
import { clip, describeError, seconds } from "./probe/format.ts";

export type Verdict = "PASS" | "FAIL";

export interface CheckResult {
  readonly id: string;
  readonly subject: string;
  readonly verdict: Verdict;
  readonly evidence: ReadonlyArray<string>;
  readonly ms: number;
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

/** One markdown table row per result, in the order given. */
export function summarize(results: ReadonlyArray<CheckResult>): string {
  return [
    "| Check | Subject | Verdict | Evidence | Wall time |",
    "| --- | --- | --- | --- | --- |",
    ...results.map(
      (result) =>
        `| ${result.id} | ${cell(result.subject)} | ${result.verdict} | ${result.evidence.map(cell).join("<br>")} | ${seconds(result.ms)} |`,
    ),
  ].join("\n");
}

const metaLine = (label: string, value: string) => `- ${label}: ${value}`;

export interface FindingsMeta {
  readonly date: string;
  readonly engineVersion: string;
  readonly claudeVersion: string;
  readonly model: string;
  readonly totalMs: number;
}

/** The whole engine-findings.md, so the file is always the output of a full run. */
export function renderFindings(
  results: ReadonlyArray<CheckResult>,
  followUps: Readonly<Record<string, string>>,
  meta: FindingsMeta,
): string {
  const failed = results.filter((result) => result.verdict === "FAIL");
  return [
    "# Engine findings",
    "",
    "Generated by `node apps/board/scripts/engine-probe.ts`. Do not edit by hand; rerun the probe.",
    "",
    metaLine("Run", meta.date),
    metaLine("Engine", `T3 ${meta.engineVersion}, isolated base dir`),
    metaLine("Provider", `Claude Code ${meta.claudeVersion}, model ${meta.model}`),
    metaLine("Full run", seconds(meta.totalMs)),
    "",
    "## Results",
    "",
    summarize(results),
    "",
    "## Follow-ups",
    "",
    ...(failed.length === 0
      ? ["No check failed, so no later PR needs a workaround."]
      : failed.map((result) => `- Check ${result.id}. ${followUps[result.id] ?? ""}`)),
    "",
  ].join("\n");
}

const CHECK_TIMEOUT_MS = 175_000;

async function runCheck(ctx: ProbeContext, spec: CheckSpec): Promise<CheckResult> {
  const evidence: string[] = [];
  const started = Date.now();
  let timer: NodeJS.Timeout | undefined;
  let verdict: Verdict;
  try {
    const { promise: timeout, reject } = Promise.withResolvers<never>();
    timer = setTimeout(
      () => reject(new Error(`check exceeded ${seconds(CHECK_TIMEOUT_MS)}`)),
      CHECK_TIMEOUT_MS,
    );
    verdict = (await Promise.race([spec.run(ctx, (line) => evidence.push(line)), timeout]))
      ? "PASS"
      : "FAIL";
  } catch (error) {
    evidence.push(
      `error: ${clip(describeError(error instanceof Error ? error : new Error(String(error))), 300)}`,
    );
    verdict = "FAIL";
  } finally {
    clearTimeout(timer);
  }
  return { id: spec.id, subject: spec.subject, verdict, evidence, ms: Date.now() - started };
}

function printResult(result: CheckResult): void {
  console.log(`${result.verdict} ${result.id} ${result.subject} (${seconds(result.ms)})`);
  for (const line of result.evidence) console.log(`    ${line}`);
}

interface Options {
  readonly checks: ReadonlyArray<string>;
  readonly runDir: string;
  readonly findings: string | null;
}

function parseOptions(argv: ReadonlyArray<string>): Options {
  const value = (flag: string) => {
    const index = argv.indexOf(flag);
    return index === -1 ? undefined : argv[index + 1];
  };
  const requested = value("--checks")
    ?.split(",")
    .map((entry) => entry.trim().toUpperCase());
  const known = CHECKS.map((spec) => spec.id);
  const checks = requested ?? known;
  const unknown = checks.filter((entry) => !known.includes(entry));
  if (unknown.length > 0)
    throw new Error(`Unknown check ${unknown.join(", ")}. Known: ${known.join(", ")}.`);
  const runDir = NodePath.resolve(
    value("--run-dir") ?? `/tmp/engine-probe/run-${Date.now().toString(36)}`,
  );
  // A partial run never overwrites the findings of a full one.
  const findings =
    value("--findings") ??
    (checks.length === known.length
      ? NodePath.resolve(import.meta.dirname, "../docs/engine-findings.md")
      : null);
  return { checks, runDir, findings: findings === null ? null : NodePath.resolve(findings) };
}

const claudeVersion = () => {
  try {
    return NodeChildProcess.execFileSync("claude", ["--version"], { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
};

async function main(): Promise<number> {
  const options = parseOptions(process.argv.slice(2));
  if (NodeFS.existsSync(options.runDir) && NodeFS.readdirSync(options.runDir).length > 0) {
    throw new Error(`${options.runDir} is not empty. Give --run-dir a new folder.`);
  }
  NodeFS.mkdirSync(options.runDir, { recursive: true });
  console.log(`probe run dir ${options.runDir}`);
  const started = Date.now();
  const engine = await startEngine(options.runDir);
  let rpc: Rpc | undefined;
  try {
    console.log(
      `isolated engine T3 ${engine.version} at ${engine.origin}, base dir ${engine.baseDir}`,
    );
    rpc = await connectRpc(engine.origin, engine.token);
    const ctx: ProbeContext = {
      rpc,
      origin: engine.origin,
      runDir: options.runDir,
      model: "claude-haiku-5-5",
      providerInstance: "claudeAgent",
    };
    const results: CheckResult[] = [];
    for (const spec of CHECKS.filter((entry) => options.checks.includes(entry.id))) {
      const result = await runCheck(ctx, spec);
      printResult(result);
      results.push(result);
    }
    const totalMs = Date.now() - started;
    console.log(
      `\n${summarize(results)}\n\nfull run ${seconds(totalMs)}, rpc reconnects ${rpc.reconnects()}`,
    );
    if (options.findings !== null) {
      const followUps = Object.fromEntries(CHECKS.map((spec) => [spec.id, spec.followUp]));
      NodeFS.writeFileSync(
        options.findings,
        renderFindings(results, followUps, {
          date: new Date().toISOString(),
          engineVersion: engine.version,
          claudeVersion: claudeVersion(),
          model: ctx.model,
          totalMs,
        }),
      );
      console.log(`wrote ${options.findings}`);
    }
    return results.every((result) => result.verdict === "PASS") ? 0 : 1;
  } finally {
    await rpc?.close().catch(() => undefined);
    await engine.stop();
    reapLeftovers(options.runDir);
    // Claude Code keeps a project folder, memory included, per working directory. A folder is the
    // probe's only if the run created it: the key drops punctuation, so a sibling path can share the prefix.
    const prefix = claudeProjectKey(options.runDir);
    const projectsDir = claudeProjectsDir();
    for (const name of NodeFS.existsSync(projectsDir) ? NodeFS.readdirSync(projectsDir) : []) {
      const folder = NodePath.join(projectsDir, name);
      if (name.startsWith(prefix) && NodeFS.statSync(folder).birthtimeMs >= started) {
        NodeFS.rmSync(folder, { recursive: true, force: true });
      }
    }
    console.log("engine stopped");
  }
}

if (import.meta.main) {
  try {
    process.exitCode = await main();
  } catch (error) {
    console.error(describeError(error instanceof Error ? error : new Error(String(error))));
    process.exitCode = 2;
  }
}
