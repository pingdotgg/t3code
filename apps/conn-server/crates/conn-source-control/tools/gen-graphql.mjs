#!/usr/bin/env node
// Generates GitHub's GraphQL operation texts from the Conn monorepo, so a change upstream
// fails `--check` instead of drifting. Never copy a query by hand.
//
//   node crates/conn-source-control/tools/gen-graphql.mjs [--check]
//
// T3 writes its GitHub reads and writes as `.graphql` files, compiles each with
// `@effect/graphql-generator` into a `.graphql.ts` module (packages/source-control-github/src/
// server), and sends what `effect/graphql` prints from the operation's document template. This
// tool imports those modules and prints every operation with Effect's own code
// (`internal/graphql.js` `joinTemplate`, the text of a single request), and keeps the template
// parts so `GraphQLResolver.aliased` batches can be rendered here. For each operation that can
// be batched it also prints Effect's `renderSlices` for two lookups (`_0_`, `_1_`): a Rust test
// holds our renderer to it.
//
// Writes crates/conn-source-control/src/hosts/github_graphql/generated.rs.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { importSource, inMonorepo, packageRequire, repoRoot } from "../../../tools/monorepo.mjs";

const check = process.argv.includes("--check");
const OUT = NodePath.join(repoRoot, "crates/conn-source-control/src/hosts/github_graphql/generated.rs");
const SOURCE_DIR = "packages/source-control-github/src/server";

// Effect's internal joiner, from the copy of `effect` the GitHub package resolves.
const effectDir = NodePath.dirname(packageRequire(SOURCE_DIR.replace(/\/src\/server$/u, "")).resolve("effect/package.json"));
const internal = await import(NodeURL.pathToFileURL(NodePath.join(effectDir, "dist/internal/graphql.js")).href);

const modules = NodeFS.readdirSync(inMonorepo(SOURCE_DIR))
  .filter((file) => file.endsWith(".graphql.ts"))
  .sort();
if (modules.length === 0) throw new Error(`no .graphql.ts modules in ${SOURCE_DIR}`);

const operations = [];
for (const file of modules) {
  const module = await importSource(`${SOURCE_DIR}/${file}`);
  for (const [exportName, value] of Object.entries(module)) {
    if (!value || typeof value !== "object" || typeof value.document !== "string") continue;
    if (!["query", "mutation"].includes(value.kind)) continue;
    if (value.name !== exportName) throw new Error(`${file}: ${exportName} names ${value.name}`);
    const template = value.template;
    if (template === undefined) throw new Error(`${file}: ${value.name} has no template`);
    const joined = internal.joinTemplate(value.kind, value.name, template);
    if (joined !== value.document) throw new Error(`${value.name}: joinTemplate differs from document`);
    const sliceable = internal.templateUnsliceableReason(template) === undefined;
    let slices = null;
    if (sliceable) {
      try {
        slices = internal.renderSlices(value.kind, value.name, template, ["_0_", "_1_"]);
      } catch {
        slices = null;
      }
    }
    operations.push({ file, operation: value, template, slices });
  }
}
operations.sort((a, b) => a.operation.name.localeCompare(b.operation.name));

const str = (value) => JSON.stringify(value);
const constName = (name) => name.replace(/([a-z0-9])([A-Z])/gu, "$1_$2").toUpperCase();
const parts = (list) => `&[${list.map(str).join(", ")}]`;

const lines = [
  "// @generated by crates/conn-source-control/tools/gen-graphql.mjs from the Conn monorepo. Do not edit.",
  "// Regenerate: node crates/conn-source-control/tools/gen-graphql.mjs",
  "//",
  `// ${operations.length} operations from ${SOURCE_DIR}/*.graphql.ts, printed by effect/graphql.`,
  "",
  "use super::{Fragment, Operation, OperationKind, Selection, Template, Variable};",
  "",
];
for (const { file, operation, template } of operations) {
  lines.push(`/// \`${operation.kind} ${operation.name}\` (${file.replace(/\.ts$/u, "")}).`);
  lines.push(`pub const ${constName(operation.name)}: Operation = Operation {`);
  lines.push(`    kind: OperationKind::${operation.kind === "query" ? "Query" : "Mutation"},`);
  lines.push(`    name: ${str(operation.name)},`);
  lines.push(`    document: ${str(operation.document)},`);
  lines.push("    template: Template {");
  lines.push(
    `        variables: &[${template.variables.map((v) => `Variable { name: ${str(v.name)}, body: ${str(v.body)} }`).join(", ")}],`,
  );
  lines.push(`        directives: ${template.directives === undefined ? "None" : `Some(${parts(template.directives)})`},`);
  lines.push(
    `        selections: &[${template.selections
      .map(
        (s) =>
          `Selection { alias: ${s.alias === undefined ? "None" : `Some(${str(s.alias)})`}, name: ${s.name === undefined ? "None" : `Some(${str(s.name)})`}, body: ${parts(s.body)} }`,
      )
      .join(", ")}],`,
  );
  lines.push(
    `        fragments: &[${template.fragments.map((f) => `Fragment { name: ${str(f.name)}, body: ${parts(f.body)} }`).join(", ")}],`,
  );
  lines.push("    },");
  lines.push("};");
  lines.push("");
}
lines.push("/// Every operation, by name.");
lines.push(`pub const ALL: &[&Operation] = &[${operations.map((o) => `&${constName(o.operation.name)}`).join(", ")}];`);
lines.push("");
lines.push("/// Effect's `renderSlices` for two lookups (`_0_`, `_1_`), per operation that can be batched.");
lines.push("#[cfg(test)]");
lines.push("pub(crate) const TWO_SLICES: &[(&str, &str)] = &[");
for (const { operation, slices } of operations) {
  if (slices !== null) lines.push(`    (${str(operation.name)}, ${str(slices)}),`);
}
lines.push("];");
lines.push("");

const code = NodeChildProcess.execFileSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
  input: lines.join("\n"),
  encoding: "utf8",
});

const current = NodeFS.existsSync(OUT) ? NodeFS.readFileSync(OUT, "utf8") : "";
if (check) {
  if (current !== code) {
    console.error(`${NodePath.relative(repoRoot, OUT)} is stale: run gen-graphql.mjs`);
    process.exit(1);
  }
  console.log(`github graphql: ${operations.length} operations current`);
} else {
  NodeFS.mkdirSync(NodePath.dirname(OUT), { recursive: true });
  NodeFS.writeFileSync(OUT, code);
  console.log(`wrote ${NodePath.relative(repoRoot, OUT)} (${operations.length} operations)`);
}
