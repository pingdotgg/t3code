#!/usr/bin/env node
// Writes src/antigravity_catalog.json: the Antigravity part of the T3 server's bundled model
// manifest (`apps/server/src/provider/model-manifest.json`), as `resolveProviderCatalog` reads
// it for the `antigravity` driver. The entry applies it as `applyModelCatalog` does (legacy
// models and the default); sessions use its default model.
//
//   node crates/conn-provider-acp/tools/gen-model-catalog.mjs [--check]
//
// `--check` exits 1 when the file is out of date. Plain JSON: no T3 code runs.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { inMonorepo } from "../../../tools/monorepo.mjs";

const HERE = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const OUT = NodePath.join(NodePath.dirname(HERE), "src", "antigravity_catalog.json");
const check = process.argv.includes("--check");

const manifest = JSON.parse(NodeFS.readFileSync(inMonorepo("apps/server/src/provider/model-manifest.json"), "utf8"));
const section = manifest.providers?.antigravity;
if (!section) {
  console.error("gen-model-catalog: the manifest has no antigravity catalog");
  process.exit(1);
}
const catalog = {
  "//": "Generated by tools/gen-model-catalog.mjs from the Conn monorepo's model-manifest.json. Do not edit.",
  defaultChatModel: section.defaults?.chat ?? null,
  models: section.models.map((entry) => ({ slug: entry.slug, status: entry.status })),
};
const text = `${JSON.stringify(catalog, null, 2)}\n`;
if (check) {
  const current = NodeFS.existsSync(OUT) ? NodeFS.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("gen-model-catalog: src/antigravity_catalog.json is out of date; run without --check");
    process.exit(1);
  }
  console.log("antigravity model catalog: up to date");
} else {
  NodeFS.writeFileSync(OUT, text);
  console.log(`wrote ${NodePath.relative(process.cwd(), OUT)}`);
}
