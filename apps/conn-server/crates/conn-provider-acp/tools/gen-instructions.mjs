#!/usr/bin/env node
// Writes src/instructions.rs: the text the T3 server puts around an ACP prompt
// (`t3AcpPromptWithInstructions` in packages/provider-core/src/server/orchestrationInstructions.ts)
// and the runtime notes it appends (`buildRuntimeInstructions` in runtimeInstructions.ts), taken
// from the monorepo so they stay byte for byte equal. Also writes
// testdata/instructions.json: what the TS functions return for a few inputs, which
// `instructions::tests` compares with the Rust build of the same values.
//
//   node crates/conn-provider-acp/tools/gen-instructions.mjs [--check]
//
// `--check` exits 1 when either file is out of date.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { inMonorepo } from "../../../tools/monorepo.mjs";

const HERE = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const CRATE = NodePath.dirname(HERE);
const check = process.argv.includes("--check");
const load = (relative) => import(NodeURL.pathToFileURL(inMonorepo(relative)).href);

const orchestration = await load("packages/provider-core/src/server/orchestrationInstructions.ts");
const runtime = await load("packages/provider-core/src/server/runtimeInstructions.ts");

/** A Rust raw string literal that holds `text` unchanged. */
const raw = (text) => {
  let hashes = "#";
  while (text.includes(`"${hashes}`)) hashes += "#";
  return `r${hashes}"${text}"${hashes}`;
};

// The wrapper is prefix + prompt + suffix; the prefix depends on the instruction state only.
const MARK = "\u0000PROMPT\u0000";
const wrap = (state) => {
  const text = orchestration.t3AcpPromptWithInstructions({ prompt: MARK, state });
  const at = text.indexOf(MARK);
  if (at < 0 || text.indexOf(MARK, at + 1) >= 0) throw new Error("prompt marker not found once");
  return { prefix: text.slice(0, at), suffix: text.slice(at + MARK.length) };
};
const states = [];
for (const interactionMode of ["default", "plan"]) {
  for (const [hasT3Mcp, hasDeviceTools] of [
    [false, false],
    [true, false],
    [true, true],
  ]) {
    states.push({ interactionMode, hasT3Mcp, hasDeviceTools, ...wrap({ interactionMode, hasT3Mcp, hasDeviceTools }) });
  }
}
const suffixes = new Set(states.map((s) => s.suffix));
if (suffixes.size !== 1) throw new Error("the prompt wrapper suffix depends on the state");

// `buildRuntimeInstructions` with marker values; the Rust side fills them in.
const HARNESS = "\u0000HARNESS\u0000";
const MODEL = "\u0000MODEL\u0000";
const template = runtime.buildRuntimeInstructions({ harness: HARNESS, model: MODEL });
const [beforeHarness, afterHarness] = template.split(HARNESS);
const [betweenHarnessAndModel, afterModel] = afterHarness.split(MODEL);
if (afterModel === undefined || !betweenHarnessAndModel.endsWith(", as ")) {
  throw new Error("buildRuntimeInstructions changed shape: update gen-instructions.mjs");
}
const harnessTail = betweenHarnessAndModel.slice(0, -", as ".length);
// Without linking (`pullRequestLinking: false`): the session's system prompt carries it.
const linking = runtime.PULL_REQUEST_LINKING_INSTRUCTIONS;
const unlinked = runtime.buildRuntimeInstructions({ harness: HARNESS, model: MODEL, pullRequestLinking: false });
if (!afterModel.endsWith(`\n\n${linking}`) || unlinked.split(MODEL)[1] !== afterModel.slice(0, -`\n\n${linking}`.length)) {
  throw new Error("buildRuntimeInstructions changed its linking part: update gen-instructions.mjs");
}
const afterModelUnlinked = afterModel.slice(0, -`\n\n${linking}`.length);

const rust = `// @generated by tools/gen-instructions.mjs from the Conn monorepo. Do not edit.
// Regenerate: node crates/conn-provider-acp/tools/gen-instructions.mjs

/// The text before the user's prompt in \`t3AcpPromptWithInstructions\`, per
/// (plan mode, has the t3-code MCP server, has device tools).
pub(crate) const PROMPT_PREFIXES: &[(bool, bool, bool, &str)] = &[
${states.map((s) => `    (${s.interactionMode === "plan"}, ${s.hasT3Mcp}, ${s.hasDeviceTools}, ${raw(s.prefix)}),`).join("\n")}
];

/// The text after the user's prompt.
pub(crate) const PROMPT_SUFFIX: &str = ${raw(states[0].suffix)};

/// \`buildRuntimeInstructions\`: the text before the harness name.
pub(crate) const RUNTIME_BEFORE_HARNESS: &str = ${raw(beforeHarness)};

/// After the harness name, before the model clause (\`, as <model>\`) or none.
pub(crate) const RUNTIME_AFTER_HARNESS: &str = ${raw(harnessTail)};

/// After the model clause.
pub(crate) const RUNTIME_AFTER_MODEL: &str = ${raw(afterModel)};

/// After the model clause when the session carries the linking text (\`pullRequestLinking: false\`).
pub(crate) const RUNTIME_AFTER_MODEL_UNLINKED: &str = ${raw(afterModelUnlinked)};

/// \`PULL_REQUEST_LINKING_INSTRUCTIONS\`: the session system prompt append of a harness that has one.
pub(crate) const PULL_REQUEST_LINKING: &str = ${raw(linking)};
`;

const samples = {
  prompts: [
    { prompt: "hello", state: { interactionMode: "default", hasT3Mcp: false, hasDeviceTools: false } },
    { prompt: "plan it", state: { interactionMode: "plan", hasT3Mcp: true, hasDeviceTools: true } },
    { prompt: "  /compact now", state: { interactionMode: "default", hasT3Mcp: true, hasDeviceTools: false } },
    {
      prompt: "same",
      state: { interactionMode: "default", hasT3Mcp: true, hasDeviceTools: false },
      previousState: { interactionMode: "default", hasT3Mcp: true, hasDeviceTools: false },
    },
    {
      prompt: "mode change",
      state: { interactionMode: "plan", hasT3Mcp: false, hasDeviceTools: false },
      previousState: { interactionMode: "default", hasT3Mcp: false, hasDeviceTools: false },
    },
  ].map((input) => ({ ...input, text: orchestration.t3AcpPromptWithInstructions(input) })),
  runtime: [
    { harness: "Grok", model: "grok-build" },
    { harness: "Kiro", model: "auto" },
    { harness: "fx", model: "default" },
    { harness: "acpRegistry", model: "  some\n model " },
    { harness: "Grok", model: "" },
    { harness: "Antigravity", model: "gemini-3.8-flash", pullRequestLinking: false },
  ].map((input) => ({ ...input, text: runtime.buildRuntimeInstructions(input) })),
};
const json = `${JSON.stringify(samples, null, 1)}\n`;

const outputs = [
  [NodePath.join(CRATE, "src/instructions.rs"), rust],
  [NodePath.join(CRATE, "testdata/instructions.json"), json],
];
let stale = 0;
for (const [file, content] of outputs) {
  const current = NodeFS.existsSync(file) ? NodeFS.readFileSync(file, "utf8") : undefined;
  if (current === content) continue;
  if (check) {
    console.error(`${NodePath.relative(CRATE, file)} is out of date: run tools/gen-instructions.mjs`);
    stale += 1;
  } else {
    NodeFS.writeFileSync(file, content);
    console.log(`wrote ${NodePath.relative(CRATE, file)}`);
  }
}
if (check && stale === 0) console.log("instructions current");
process.exit(stale === 0 ? 0 : 1);
