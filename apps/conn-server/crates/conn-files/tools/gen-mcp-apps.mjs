// Kept byte for byte from the client's MCP App bootstrap helpers.
import * as fs from "node:fs";
import { fileURLToPath } from "node:url";
import { importSource } from "../../../tools/monorepo.mjs";
export function generateBootstrap(shared, check) {
  const bootstrap = shared.injectMcpAppCookieBootstrap(shared.injectMcpAppThemeBootstrap("")).replace(/^<!doctype html>/, "");
  const generated = `// Generated by tools/gen-mcp-apps.mjs; do not edit.\npub(crate) const BOOTSTRAP: &str = r###"${bootstrap}"###;\n`;
  const file = new URL("../src/mcp_app_bootstrap.rs", import.meta.url);
  if (check) { if (fs.readFileSync(file,"utf8") !== generated) throw new Error("MCP App bootstrap drift: run node crates/conn-files/tools/gen-mcp-apps.mjs"); }
  else fs.writeFileSync(file,generated);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generateBootstrap(await importSource("packages/shared/src/mcpApp.ts"),process.argv.includes("--check"));
