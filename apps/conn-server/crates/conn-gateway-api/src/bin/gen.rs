//! Generates `src/types.rs` and `src/ops.rs` from `openapi.json` and `operations.txt`.
//!
//! ```sh
//! cargo run -p conn-gateway-api --features gen                    # regenerate from the pin
//! cargo run -p conn-gateway-api --features gen -- --check         # fail when src/ is stale
//! CONN_UNSEALED=1 cargo run -p conn-gateway-api --features gen -- --fetch https://gateway.orbit
//! ```
//!
//! `--fetch` reads `GET <url>/api/v1/openapi.json` with the system `curl` (the Gateway's CA is
//! in the system trust store on mini), checks the body against `X-Orbit-OpenAPI-SHA256`, and
//! writes `openapi.json` and `openapi.source` before it regenerates.
//!
//! The generator does not edit the document. It rewrites a copy for typify: `$ref`s point at
//! `#/definitions/`, value checks (`pattern`, lengths, bounds, `format`) and `x-*` keys go, and an
//! untyped `{"type": "object"}` becomes `serde_json::Value` marked `TODO(6200)`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use serde_json::{Map, Value, json};
use sha2::{Digest, Sha256};

type Result<T> = std::result::Result<T, String>;

const UNTYPED: &str = "TODO(6200): an untyped object in the Gateway document; typed once Orbit \
                       group 6200 documents it.";
const STRIPPED: &[&str] = &[
    "pattern",
    "minLength",
    "maxLength",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "multipleOf",
    "minItems",
    "maxItems",
    "uniqueItems",
    "minProperties",
    "maxProperties",
    "format",
    "example",
    "examples",
];
const MANAGED_PREFIX: &str = "/api/v1/conn/managed/";
type AddedField = (&'static str, &'static str, fn() -> Value);

/// Fields a newer Gateway added as required, which older live Gateways still omit. Each one is
/// made optional with this default, so both decode until the fleet rollout is done.
const ADDED_FIELDS: &[AddedField] = &[
    ("ConnEnvironment", "is_primary_agent", || json!(false)),
    ("ConnEnvironment", "roles", || json!([])),
];
const HEADER: &str = "// @generated by `cargo run -p conn-gateway-api --features gen`. Do not edit.\n\
                      // Source: openapi.json and operations.txt in this crate.\n";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("conn-gateway-api-gen: {message}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<()> {
    let mut check = false;
    let mut fetch = None;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--fetch" => fetch = Some(args.next().ok_or("--fetch needs a Gateway URL")?),
            _ => {
                return Err(format!(
                    "unknown argument {arg:?}; usage: [--fetch <url>] [--check]"
                ));
            }
        }
    }
    if check && fetch.is_some() {
        return Err("--check reads the pin only; drop --fetch".into());
    }
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    if let Some(url) = fetch {
        fetch_document(&root, &url)?;
    }

    let document_bytes = read(&root.join("openapi.json"))?;
    let digest = sha256_hex(&document_bytes);
    let source = read_text(&root.join("openapi.source"))?;
    let pinned = source_value(&source, "sha256").ok_or("openapi.source has no sha256")?;
    if pinned != digest {
        return Err(format!(
            "openapi.source says sha256 {pinned}, openapi.json is {digest}: the digest is stale"
        ));
    }
    let document: Value = serde_json::from_slice(&document_bytes)
        .map_err(|error| format!("openapi.json: {error}"))?;
    let ids = operation_ids(&read_text(&root.join("operations.txt"))?)?;

    let model = Model::build(&document, &ids, ADDED_FIELDS)?;
    let types = model.types_rs()?;
    let ops = model.ops_rs(&digest)?;

    let outputs = [
        (root.join("src/types.rs"), types),
        (root.join("src/ops.rs"), ops),
    ];
    if check {
        let stale: Vec<String> = outputs
            .iter()
            .filter(|(path, text)| std::fs::read_to_string(path).ok().as_deref() != Some(text))
            .map(|(path, _)| path.display().to_string())
            .collect();
        if !stale.is_empty() {
            return Err(format!(
                "stale generation: {}. Run `cargo run -p conn-gateway-api --features gen`.",
                stale.join(", ")
            ));
        }
        println!("conn-gateway-api: generation matches openapi.json ({digest})");
    } else {
        for (path, text) in &outputs {
            std::fs::write(path, text).map_err(|error| format!("{}: {error}", path.display()))?;
        }
        println!("conn-gateway-api: wrote src/types.rs and src/ops.rs ({digest})");
    }
    Ok(())
}

// ---------------------------------------------------------------- inputs

fn read(path: &Path) -> Result<Vec<u8>> {
    std::fs::read(path).map_err(|error| format!("{}: {error}", path.display()))
}

fn read_text(path: &Path) -> Result<String> {
    std::fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))
}

fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::with_capacity(64), |mut out, byte| {
            let _ = write!(out, "{byte:02x}");
            out
        })
}

/// `key = "value"` from `openapi.source`.
fn source_value<'a>(source: &'a str, key: &str) -> Option<&'a str> {
    source.lines().find_map(|line| {
        let (name, value) = line.split_once('=')?;
        (name.trim() == key).then(|| value.trim().trim_matches('"'))
    })
}

fn operation_ids(text: &str) -> Result<Vec<String>> {
    let mut seen = BTreeSet::new();
    let mut ids = Vec::new();
    for line in text.lines() {
        let id = line.split('#').next().unwrap_or_default().trim();
        if id.is_empty() {
            continue;
        }
        if !seen.insert(id.to_owned()) {
            return Err(format!("operations.txt lists {id} twice"));
        }
        ids.push(id.to_owned());
    }
    ids.sort();
    Ok(ids)
}

fn fetch_document(root: &Path, gateway: &str) -> Result<()> {
    let url = format!("{}/api/v1/openapi.json", gateway.trim_end_matches('/'));
    let dir = std::env::temp_dir().join(format!("conn-gateway-api-fetch-{}", std::process::id()));
    std::fs::create_dir_all(&dir).map_err(|error| format!("{}: {error}", dir.display()))?;
    let headers_path = dir.join("headers");
    let body_path = dir.join("body");
    let status = Command::new("curl")
        .args([
            "--silent",
            "--show-error",
            "--fail",
            "--max-time",
            "60",
            "--dump-header",
        ])
        .arg(&headers_path)
        .arg("--output")
        .arg(&body_path)
        .arg(&url)
        .status()
        .map_err(|error| format!("curl: {error}"));
    let result = status.and_then(|status| {
        if !status.success() {
            return Err(format!("curl {url} failed ({status})"));
        }
        let headers = read_text(&headers_path)?;
        let body = read(&body_path)?;
        let header = |name: &str| {
            headers.lines().find_map(|line| {
                let (key, value) = line.split_once(':')?;
                key.trim()
                    .eq_ignore_ascii_case(name)
                    .then(|| value.trim().to_owned())
            })
        };
        let served = header("x-orbit-openapi-sha256")
            .ok_or_else(|| format!("{url} sent no X-Orbit-OpenAPI-SHA256 header"))?;
        let digest = sha256_hex(&body);
        if !served.eq_ignore_ascii_case(&digest) {
            return Err(format!(
                "{url}: X-Orbit-OpenAPI-SHA256 is {served}, the body is {digest}"
            ));
        }
        serde_json::from_slice::<Value>(&body).map_err(|error| format!("{url}: {error}"))?;
        let mut source = format!(
            "# Where openapi.json came from. Written by `--fetch`; checked by `--check`.\n\
             source = \"{url}\"\n"
        );
        if let Some(commit) = header("x-orbit-commit") {
            let _ = writeln!(source, "orbit_commit = \"{commit}\"");
        }
        let _ = writeln!(source, "sha256 = \"{digest}\"");
        std::fs::write(root.join("openapi.json"), &body).map_err(|error| error.to_string())?;
        std::fs::write(root.join("openapi.source"), source).map_err(|error| error.to_string())?;
        println!("conn-gateway-api: fetched {url} ({digest})");
        Ok(())
    });
    let _ = std::fs::remove_dir_all(&dir);
    result
}

// ---------------------------------------------------------------- schema rewrite

/// A copy of `schema` that typify reads as Conn wants it. Counts the untyped objects.
fn normalize(schema: &Value, untyped: &mut usize) -> Value {
    let Value::Object(map) = schema else {
        return schema.clone();
    };
    let is_untyped_object = map.get("type") == Some(&json!("object"))
        && map
            .keys()
            .all(|key| matches!(key.as_str(), "type" | "description" | "title"));
    if is_untyped_object {
        *untyped += 1;
        let description = match map.get("description").and_then(Value::as_str) {
            Some(text) => format!("{text}\n\n{UNTYPED}"),
            None => UNTYPED.to_owned(),
        };
        return json!({ "description": description });
    }
    let mut out = Map::new();
    for (key, value) in map {
        let key_str = key.as_str();
        if STRIPPED.contains(&key_str) || key_str.starts_with("x-") {
            continue;
        }
        let value = match key_str {
            "$ref" => match value.as_str() {
                Some(target) => json!(format!("#/definitions/{}", ref_name(target))),
                None => value.clone(),
            },
            "properties" | "patternProperties" | "$defs" | "definitions" => match value {
                Value::Object(children) => Value::Object(
                    children
                        .iter()
                        .map(|(name, child)| (name.clone(), normalize(child, untyped)))
                        .collect(),
                ),
                _ => value.clone(),
            },
            "oneOf" | "anyOf" | "allOf" | "prefixItems" => match value {
                Value::Array(items) => {
                    Value::Array(items.iter().map(|item| normalize(item, untyped)).collect())
                }
                _ => value.clone(),
            },
            "items"
            | "additionalProperties"
            | "not"
            | "contains"
            | "propertyNames"
            | "if"
            | "then"
            | "else" => normalize(value, untyped),
            _ => value.clone(),
        };
        out.insert(key.clone(), value);
    }
    Value::Object(out)
}

fn ref_name(target: &str) -> &str {
    target.rsplit('/').next().unwrap_or(target)
}

fn collect_refs(schema: &Value, refs: &mut BTreeSet<String>) {
    match schema {
        Value::Object(map) => {
            for (key, value) in map {
                if key == "$ref" {
                    if let Some(target) = value.as_str() {
                        refs.insert(ref_name(target).to_owned());
                    }
                } else {
                    collect_refs(value, refs);
                }
            }
        }
        Value::Array(items) => items.iter().for_each(|item| collect_refs(item, refs)),
        _ => {}
    }
}

// ---------------------------------------------------------------- model

#[derive(Debug)]
struct Param {
    name: String,
    field: String,
    location: Location,
    ty: ParamType,
    required: bool,
    description: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Location {
    Path,
    Query,
    Header,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ParamType {
    Integer,
    Boolean,
    Text,
}

impl ParamType {
    fn rust(self) -> &'static str {
        match self {
            Self::Integer => "i64",
            Self::Boolean => "bool",
            Self::Text => "String",
        }
    }
}

#[derive(Debug)]
enum Success {
    /// Every 2xx status answers this generated type.
    One(String),
    /// No 2xx status has a body.
    Empty,
    /// The statuses differ: an enum in ops.rs, variant per status with its type, if any.
    ByStatus(Vec<(u16, Option<String>)>),
}

#[derive(Debug)]
struct Operation {
    id: String,
    pascal: String,
    method: &'static str,
    path: String,
    summary: Option<String>,
    params: Vec<Param>,
    body: Option<(String, bool)>,
    success_statuses: Vec<u16>,
    success: Success,
    error_statuses: Vec<u16>,
    error_type: String,
    managed: bool,
    untyped: usize,
}

#[derive(Debug)]
struct Model {
    operations: Vec<Operation>,
    definitions: BTreeMap<String, Value>,
    untyped_components: BTreeSet<String>,
}

impl Model {
    fn build(document: &Value, ids: &[String], added_fields: &[AddedField]) -> Result<Self> {
        let paths = document
            .get("paths")
            .and_then(Value::as_object)
            .ok_or("no paths")?;
        let components = document
            .pointer("/components/schemas")
            .and_then(Value::as_object)
            .ok_or("no components.schemas")?;
        let mut found = BTreeMap::new();
        for (path, item) in paths {
            let Some(item) = item.as_object() else {
                continue;
            };
            for (method, operation) in item {
                if let Some(id) = operation.get("operationId").and_then(Value::as_str) {
                    found.insert(id.to_owned(), (method.clone(), path.clone(), operation));
                }
            }
        }

        let document_security = document.get("security");
        let mut definitions = BTreeMap::new();
        let mut operations = Vec::new();
        for id in ids {
            let (method, path, operation) = found
                .get(id)
                .ok_or_else(|| format!("operations.txt: {id} is not in openapi.json"))?;
            let security = operation.get("security").or(document_security);
            let built = build_operation(id, method, path, operation, security, &mut definitions)
                .map_err(|error| format!("{id}: {error}"))?;
            operations.push(built);
        }

        let mut pending = BTreeSet::new();
        definitions
            .values()
            .for_each(|schema| collect_refs(schema, &mut pending));
        pending.extend(operations.iter().map(|op| op.error_type.clone()));
        let mut untyped_components = BTreeSet::new();
        while let Some(name) = pending.pop_first() {
            if definitions.contains_key(&name) {
                continue;
            }
            let schema = components
                .get(&name)
                .ok_or_else(|| format!("$ref to missing component {name}"))?;
            let mut untyped = 0;
            let normalized = normalize(schema, &mut untyped);
            if untyped > 0 {
                untyped_components.insert(name.clone());
            }
            collect_refs(&normalized, &mut pending);
            definitions.insert(name, normalized);
        }
        for (schema, field, default) in added_fields {
            let definition = definitions.get_mut(*schema).ok_or_else(|| {
                format!("ADDED_FIELDS names {schema}, which no listed operation uses")
            })?;
            default_added_field(definition, field, default())
                .map_err(|error| format!("{schema}.{field}: {error}"))?;
        }
        Ok(Self {
            operations,
            definitions,
            untyped_components,
        })
    }

    fn types_rs(&self) -> Result<String> {
        let mut definitions = schemars::Map::new();
        for (name, schema) in &self.definitions {
            let schema: schemars::schema::Schema = serde_json::from_value(schema.clone())
                .map_err(|error| format!("schema {name}: {error}"))?;
            definitions.insert(name.clone(), schema);
        }
        let mut space = typify::TypeSpace::new(&typify::TypeSpaceSettings::default());
        space
            .add_root_schema(schemars::schema::RootSchema {
                meta_schema: None,
                schema: schemars::schema::SchemaObject::default(),
                definitions,
            })
            .map_err(|error| format!("typify: {error}"))?;
        let tokens = space
            .to_stream()
            .map_err(|error| format!("typify: {error}"))?;
        let file: syn::File =
            syn::parse2(tokens).map_err(|error| format!("typify output: {error}"))?;
        Ok(format!(
            "{HEADER}//! Serde types for the schemas the operations in `operations.txt` use.\n\n{}",
            prettyplease::unparse(&file)
        ))
    }

    fn ops_rs(&self, digest: &str) -> Result<String> {
        let mut code = String::new();
        let _ = writeln!(
            code,
            "/// sha256 of `openapi.json`, the document this code comes from."
        );
        let _ = writeln!(code, "pub const OPENAPI_SHA256: &str = {digest:?};");
        let _ = writeln!(code, "/// The `operationId` of every generated operation.");
        let ids: Vec<String> = self
            .operations
            .iter()
            .map(|op| format!("{:?}", op.id))
            .collect();
        let _ = writeln!(
            code,
            "pub const OPERATION_IDS: &[&str] = &[{}];",
            ids.join(", ")
        );
        for op in &self.operations {
            self.write_operation(&mut code, op);
        }
        let file: syn::File = syn::parse_file(&code).map_err(|error| format!("ops.rs: {error}"))?;
        Ok(format!(
            "{HEADER}//! One struct per Gateway operation in `operations.txt`.\n\n{}",
            prettyplease::unparse(&file)
        ))
    }

    fn write_operation(&self, code: &mut String, op: &Operation) {
        let name = &op.pascal;
        let mut doc = format!("`{} {}`", op.method.to_uppercase(), op.path);
        if let Some(summary) = &op.summary {
            let _ = write!(doc, ": {summary}");
        }
        let untyped_refs = self.untyped_refs(op);
        if op.untyped > 0 || !untyped_refs.is_empty() {
            let mut note = String::from(
                " TODO(6200): this operation's schemas hold untyped objects (`serde_json::Value`)",
            );
            if !untyped_refs.is_empty() {
                let _ = write!(note, ", also in {}", untyped_refs.join(", "));
            }
            note.push('.');
            let _ = write!(doc, "\n\n{note}");
        }
        let _ = writeln!(code, "#[doc = {doc:?}]");
        if op.params.is_empty() && op.body.is_none() {
            let _ = writeln!(
                code,
                "#[derive(Debug, Clone, Copy, Default)]\npub struct {name};"
            );
        } else {
            write_fields(code, op);
        }
        self.write_operation_impl(code, op);
    }
}

fn write_fields(code: &mut String, op: &Operation) {
    {
        let _ = writeln!(code, "#[derive(Debug, Clone)]\npub struct {} {{", op.pascal);
        for param in &op.params {
            if let Some(description) = &param.description {
                let _ = writeln!(code, "#[doc = {:?}]", format!(" {description}"));
            }
            let ty = param.ty.rust();
            let ty = if param.required {
                ty.to_owned()
            } else {
                format!("Option<{ty}>")
            };
            let _ = writeln!(code, "pub {}: {ty},", param.field);
        }
        if let Some((body, required)) = &op.body {
            let ty = format!("crate::types::{body}");
            let ty = if *required {
                ty
            } else {
                format!("Option<{ty}>")
            };
            let _ = writeln!(code, "pub body: {ty},");
        }
        code.push_str("}\n");
    }
}

impl Model {
    fn write_operation_impl(&self, code: &mut String, op: &Operation) {
        let name = &op.pascal;
        let success_type = match &op.success {
            Success::One(ty) => format!("crate::types::{ty}"),
            Success::Empty => "()".to_owned(),
            Success::ByStatus(variants) => {
                let _ = writeln!(
                    code,
                    "#[doc = {:?}]\n#[derive(Debug, Clone)]\npub enum {name}Success {{",
                    format!(" A 2xx answer of [`{name}`], by status.")
                );
                for (status, ty) in variants {
                    match ty {
                        Some(ty) => {
                            let _ = writeln!(code, "Status{status}(Box<crate::types::{ty}>),");
                        }
                        None => {
                            let _ = writeln!(code, "Status{status},");
                        }
                    }
                }
                code.push_str("}\n");
                format!("{name}Success")
            }
        };

        let auth = if op.managed {
            "ManagedBearer"
        } else {
            "WireGuardPeer"
        };
        let method = match op.method {
            "get" => "Get",
            "post" => "Post",
            "put" => "Put",
            "patch" => "Patch",
            _ => "Delete",
        };
        let statuses = |list: &[u16]| {
            list.iter()
                .map(u16::to_string)
                .collect::<Vec<_>>()
                .join(", ")
        };
        let body_type = match &op.body {
            Some((body, _)) => format!("crate::types::{body}"),
            None => "crate::NoBody".to_owned(),
        };
        let _ = writeln!(
            code,
            "impl crate::GatewayOperation for {name} {{\n\
             const ID: &'static str = {id:?};\n\
             const METHOD: crate::Method = crate::Method::{method};\n\
             const PATH_TEMPLATE: &'static str = {path:?};\n\
             const AUTH: crate::AuthKind = crate::AuthKind::{auth};\n\
             const SUCCESS_STATUSES: &'static [u16] = &[{success}];\n\
             const ERROR_STATUSES: &'static [u16] = &[{errors}];\n\
             type Body = {body_type};\n\
             type Success = {success_type};\n\
             type Error = crate::types::{error};",
            id = op.id,
            path = op.path,
            success = statuses(&op.success_statuses),
            errors = statuses(&op.error_statuses),
            error = op.error_type,
        );
        let _ = writeln!(
            code,
            "fn path(&self) -> String {{ {} }}",
            path_expression(op)
        );
        let _ = writeln!(
            code,
            "fn query(&self) -> Vec<(&'static str, String)> {{ {} }}",
            pairs_expression(op, Location::Query)
        );
        let _ = writeln!(
            code,
            "fn headers(&self) -> Vec<(&'static str, String)> {{ {} }}",
            pairs_expression(op, Location::Header)
        );
        let body = match &op.body {
            Some((_, true)) => "Some(&self.body)",
            Some((_, false)) => "self.body.as_ref()",
            None => "None",
        };
        let _ = writeln!(code, "fn body(&self) -> Option<&Self::Body> {{ {body} }}");
        let _ = writeln!(code, "{}\n}}", decode_success(op, &success_type));
    }

    fn untyped_refs(&self, op: &Operation) -> Vec<String> {
        let mut refs = BTreeSet::new();
        let own = [
            op.body.as_ref().map(|(name, _)| name.clone()),
            match &op.success {
                Success::One(ty) => Some(ty.clone()),
                _ => None,
            },
        ];
        let mut roots: Vec<String> = own.into_iter().flatten().collect();
        if let Success::ByStatus(variants) = &op.success {
            roots.extend(variants.iter().filter_map(|(_, ty)| ty.clone()));
        }
        roots.push(op.error_type.clone());
        let mut seen = BTreeSet::new();
        while let Some(name) = roots.pop() {
            if !seen.insert(name.clone()) {
                continue;
            }
            if let Some(schema) = self.definitions.get(&name) {
                let mut found = BTreeSet::new();
                collect_refs(schema, &mut found);
                roots.extend(found);
            }
            if self.untyped_components.contains(&name) {
                refs.insert(format!("`{name}`"));
            }
        }
        refs.into_iter().collect()
    }
}

fn pascal(id: &str) -> String {
    id.split(['-', '_', '.', ':'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| format!("{}{}", first.to_ascii_uppercase(), chars.as_str()))
                .unwrap_or_default()
        })
        .collect()
}

fn field_name(name: &str) -> String {
    let snake: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    match snake.as_str() {
        "type" | "match" | "ref" | "self" | "struct" | "enum" | "fn" | "mod" | "use" | "impl"
        | "in" | "where" | "loop" | "move" | "async" | "await" | "dyn" => format!("r#{snake}"),
        _ => snake,
    }
}

fn build_operation(
    id: &str,
    method: &str,
    path: &str,
    operation: &Value,
    security: Option<&Value>,
    definitions: &mut BTreeMap<String, Value>,
) -> Result<Operation> {
    let method: &'static str = match method {
        "get" => "get",
        "post" => "post",
        "put" => "put",
        "patch" => "patch",
        "delete" => "delete",
        other => return Err(format!("method {other} is not supported")),
    };
    let pascal = pascal(id);
    let mut untyped = 0;

    let mut params = Vec::new();
    for param in operation
        .get("parameters")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        let name = param
            .get("name")
            .and_then(Value::as_str)
            .ok_or("parameter without name")?;
        let location = match param.get("in").and_then(Value::as_str) {
            Some("path") => Location::Path,
            Some("query") => Location::Query,
            Some("header") => Location::Header,
            other => return Err(format!("parameter {name} in {other:?} is not supported")),
        };
        // A nullable query value (`["string", "null"]`) is the same as leaving it out.
        let ty = match param.pointer("/schema/type") {
            Some(Value::Array(types)) => types
                .iter()
                .filter_map(Value::as_str)
                .find(|ty| *ty != "null"),
            other => other.and_then(Value::as_str),
        };
        let ty = match ty {
            Some("integer") => ParamType::Integer,
            Some("boolean") => ParamType::Boolean,
            Some("string") => ParamType::Text,
            other => {
                return Err(format!(
                    "parameter {name} of type {other:?} is not supported"
                ));
            }
        };
        let required = location == Location::Path
            || param
                .get("required")
                .and_then(Value::as_bool)
                .unwrap_or(false);
        params.push(Param {
            name: name.to_owned(),
            field: field_name(name),
            location,
            ty,
            required,
            description: param
                .get("description")
                .and_then(Value::as_str)
                .map(str::trim)
                .filter(|text| !text.is_empty())
                .map(str::to_owned),
        });
    }
    for placeholder in placeholders(path) {
        if !params
            .iter()
            .any(|p| p.location == Location::Path && p.name == placeholder)
        {
            return Err(format!(
                "path placeholder {{{placeholder}}} has no parameter"
            ));
        }
    }

    let body = match operation.get("requestBody") {
        Some(request) => {
            let schema = request
                .pointer("/content/application~1json/schema")
                .ok_or("request body without application/json schema")?;
            let name = format!("{pascal}Request");
            insert_definition(definitions, &name, normalize(schema, &mut untyped))?;
            let required = request
                .get("required")
                .and_then(Value::as_bool)
                .unwrap_or(false);
            Some((name, required))
        }
        None => None,
    };

    let responses = operation
        .get("responses")
        .and_then(Value::as_object)
        .ok_or("no responses")?;
    let mut successes: Vec<(u16, Option<Value>)> = Vec::new();
    let mut error_statuses = Vec::new();
    let mut error_types = BTreeSet::new();
    for (code, response) in responses {
        let status: u16 = code
            .parse()
            .map_err(|_| format!("response code {code} is not a status"))?;
        let schema = response.pointer("/content/application~1json/schema");
        if (200..300).contains(&status) {
            successes.push((status, schema.map(|schema| normalize(schema, &mut untyped))));
        } else {
            let target = schema
                .and_then(|schema| schema.get("$ref"))
                .and_then(Value::as_str)
                .ok_or_else(|| format!("error {status} is not a $ref"))?;
            error_types.insert(ref_name(target).to_owned());
            error_statuses.push(status);
        }
    }
    successes.sort_by_key(|(status, _)| *status);
    error_statuses.sort_unstable();
    let error_type = match error_types.len() {
        1 => error_types.pop_first().unwrap_or_default(),
        0 => "Error".to_owned(),
        _ => return Err(format!("several error types: {error_types:?}")),
    };

    let success_statuses: Vec<u16> = successes.iter().map(|(status, _)| *status).collect();
    let success = match successes.as_slice() {
        [] => return Err("no 2xx response".into()),
        list if list.iter().all(|(_, schema)| schema.is_none()) => Success::Empty,
        [(_, Some(first)), rest @ ..] if rest.iter().all(|(_, s)| s.as_ref() == Some(first)) => {
            let name = format!("{pascal}Response");
            insert_definition(definitions, &name, first.clone())?;
            Success::One(name)
        }
        list => {
            let mut variants = Vec::new();
            for (status, schema) in list {
                let ty = match schema {
                    Some(schema) => {
                        let name = format!("{pascal}Response{status}");
                        insert_definition(definitions, &name, schema.clone())?;
                        Some(name)
                    }
                    None => None,
                };
                variants.push((*status, ty));
            }
            Success::ByStatus(variants)
        }
    };

    let managed = managed_auth(security)?;
    if managed != path.starts_with(MANAGED_PREFIX) {
        return Err(format!(
            "`security` and the {MANAGED_PREFIX} path disagree about the managed bearer"
        ));
    }

    Ok(Operation {
        id: id.to_owned(),
        pascal,
        method,
        path: path.to_owned(),
        summary: operation
            .get("summary")
            .and_then(Value::as_str)
            .map(str::to_owned),
        params,
        body,
        success_statuses,
        success,
        error_statuses,
        error_type,
        managed,
        untyped,
    })
}

/// True when the route's effective `security` (its own, else the document's) asks for the managed
/// bearer. No `security` anywhere means the WireGuard peer only.
fn managed_auth(security: Option<&Value>) -> Result<bool> {
    let Some(security) = security else {
        return Ok(false);
    };
    let requirements = security.as_array().ok_or("`security` is not a list")?;
    if requirements.len() != 1 {
        return Err(format!(
            "`security` lists {} requirements; AuthKind maps exactly one",
            requirements.len()
        ));
    }
    let schemes = requirements[0]
        .as_object()
        .ok_or("a `security` requirement is not an object")?;
    let mut managed = false;
    for scheme in schemes.keys() {
        match scheme.as_str() {
            "wireguardPeer" => {}
            "managedTargetBearer" => managed = true,
            other => return Err(format!("`security` scheme {other} has no AuthKind")),
        }
    }
    if !schemes.contains_key("wireguardPeer") {
        return Err("`security` drops the WireGuard peer; AuthKind assumes it".into());
    }
    Ok(managed)
}

/// Drops `field` from `definition`'s `required` list and gives it `default`.
fn default_added_field(definition: &mut Value, field: &str, default: Value) -> Result<()> {
    let property = definition
        .pointer_mut(&format!("/properties/{field}"))
        .and_then(Value::as_object_mut)
        .ok_or("the schema has no such property; drop it from ADDED_FIELDS")?;
    property.insert("default".to_owned(), default);
    if let Some(required) = definition.get_mut("required").and_then(Value::as_array_mut) {
        required.retain(|name| name.as_str() != Some(field));
    }
    Ok(())
}

fn insert_definition(defs: &mut BTreeMap<String, Value>, name: &str, schema: Value) -> Result<()> {
    if defs.insert(name.to_owned(), schema).is_some() {
        return Err(format!("two schemas are named {name}"));
    }
    Ok(())
}

fn placeholders(path: &str) -> Vec<&str> {
    path.split('{')
        .skip(1)
        .filter_map(|part| part.split_once('}').map(|(name, _)| name))
        .collect()
}

fn path_expression(op: &Operation) -> String {
    let names = placeholders(&op.path);
    if names.is_empty() {
        return format!("{:?}.to_owned()", op.path);
    }
    let mut template = op.path.clone();
    let mut args = Vec::new();
    for name in names {
        template = template.replacen(&format!("{{{name}}}"), "{}", 1);
        let param = op
            .params
            .iter()
            .find(|p| p.location == Location::Path && p.name == name);
        let field = param.map(|p| p.field.clone()).unwrap_or_default();
        let value = match param.map(|p| p.ty) {
            Some(ParamType::Text) => format!("&self.{field}"),
            _ => format!("&self.{field}.to_string()"),
        };
        args.push(format!("crate::encode_component({value})"));
    }
    format!("format!({template:?}, {})", args.join(", "))
}

fn pairs_expression(op: &Operation, location: Location) -> String {
    let items: Vec<String> = op
        .params
        .iter()
        .filter(|p| p.location == location)
        .map(|p| {
            let (name, field) = (&p.name, &p.field);
            let convert = if p.ty == ParamType::Text {
                "clone()"
            } else {
                "to_string()"
            };
            if p.required {
                format!("Some(({name:?}, self.{field}.{convert}))")
            } else {
                format!("self.{field}.as_ref().map(|value| ({name:?}, value.{convert}))")
            }
        })
        .collect();
    if items.is_empty() {
        "Vec::new()".to_owned()
    } else {
        format!("[{}].into_iter().flatten().collect()", items.join(", "))
    }
}

fn decode_success(op: &Operation, success_type: &str) -> String {
    let statuses = op
        .success_statuses
        .iter()
        .map(u16::to_string)
        .collect::<Vec<_>>()
        .join(" | ");
    let arms = match &op.success {
        Success::One(_) => format!("{statuses} => crate::decode_json(status, body),"),
        Success::Empty => format!("{statuses} => Ok(()),"),
        Success::ByStatus(variants) => variants
            .iter()
            .map(|(status, ty)| match ty {
                Some(_) => format!(
                    "{status} => crate::decode_json(status, body).map(|value| {success_type}::Status{status}(Box::new(value))),"
                ),
                None => format!("{status} => Ok({success_type}::Status{status}),"),
            })
            .collect::<Vec<_>>()
            .join("\n"),
    };
    let uses_body = !matches!(op.success, Success::Empty);
    let body_name = if uses_body { "body" } else { "_body" };
    format!(
        "fn decode_success(status: u16, {body_name}: &[u8]) -> Result<Self::Success, crate::DecodeError> {{\n\
         match status {{\n{arms}\n_ => Err(crate::DecodeError::UnexpectedStatus(status)),\n}}\n}}"
    )
}

