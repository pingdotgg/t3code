#!/usr/bin/env node
// Writes src/model_catalog.json: the Codex part of the T3 server's bundled model manifest
// (`apps/server/src/provider/model-manifest.json`), as `resolveProviderCatalog` reads it for
// the `codex` driver. The status probe applies it as `applyCodexModelCatalog` does (legacy
// models, the default, and models that need a newer CLI).
//
//   node crates/conn-provider-codex/tools/gen-model-catalog.mjs [--check]
//
// `--check` exits 1 when the file is out of date. Plain JSON: no T3 code runs.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { inMonorepo } from "../../../tools/monorepo.mjs";

const HERE = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const OUT = NodePath.join(NodePath.dirname(HERE), "src", "model_catalog.json");
const check = process.argv.includes("--check");

const manifest = JSON.parse(NodeFS.readFileSync(inMonorepo("apps/server/src/provider/model-manifest.json"), "utf8"));
const codex = manifest.providers?.codex;
if (!codex) {
  console.error("gen-model-catalog: the manifest has no codex catalog");
  process.exit(1);
}
const catalog = {
  "//": "Generated by tools/gen-model-catalog.mjs from the Conn monorepo's model-manifest.json. Do not edit.",
  defaultChatModel: codex.defaults?.chat ?? null,
  models: codex.models.map((entry) => {
    const profile = entry.profile ? codex.profiles?.[entry.profile] : undefined;
    return {
      slug: entry.slug,
      name: entry.name,
      ...(entry.shortName ? { shortName: entry.shortName } : {}),
      ...(entry.subProvider ? { subProvider: entry.subProvider } : {}),
      ...(entry.aliases ? { aliases: entry.aliases } : {}),
      // The "new" badge depends on the clock; the probe computes it from this date.
      ...(entry.releasedAt ? { releasedAt: entry.releasedAt } : {}),
      status: entry.status,
      capabilities: profile?.capabilities ?? null,
      minVersion: entry.adapter?.codex?.minVersion?.trim() || null,
    };
  }),
};
const text = `${JSON.stringify(catalog, null, 2)}\n`;
if (check) {
  const current = NodeFS.existsSync(OUT) ? NodeFS.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("gen-model-catalog: src/model_catalog.json is out of date; run without --check");
    process.exit(1);
  }
  console.log("codex model catalog: up to date");
} else {
  NodeFS.writeFileSync(OUT, text);
  console.log(`wrote ${NodePath.relative(process.cwd(), OUT)}`);
}
