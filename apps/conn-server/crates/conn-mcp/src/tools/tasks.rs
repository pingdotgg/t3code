//! Delegated tasks: `delegate_task`, `task_status`, `task_cancel`.
//!
//! `delegate_task` dispatches the engine's `delegated_task.request`, which writes the child
//! thread (lineage `subagent`), the parent's subagent rows and the child's first run, and
//! wakes the parent when the child ends. Ids follow from the command id (engine README), so
//! no table keeps tasks: task `node:delegated-task:<commandId>`, child
//! `thread:delegated-task:<commandId>`.

use std::{path::Path, time::Duration};

use serde_json::{Value, json};

use super::{
    Args, Cx, ToolError, ToolResult, fail, str_arg,
    threads::{self, MAX_WAIT_MS},
};
use crate::{Caller, view};

const DEFAULT_TASK_WAIT_MS: u64 = 4 * 60 * 1000;
/// `ORCHESTRATOR_MCP_RUNNING_TASK_NEXT`, generated by `tools/gen-tools.mjs`: the schema takes
/// any string since b12470dcad, so the catalog does not hold it.
pub(super) const RUNNING_TASK_NEXT: &str = include_str!("../running-task-next.txt");
pub(super) const TERMINAL: [&str; 4] = ["completed", "failed", "cancelled", "interrupted"];
const TASK_PREFIX: &str = "node:delegated-task:";

/// TS `taskStatusForRun`.
fn task_status(run: Option<&Value>) -> &'static str {
    match run.and_then(|r| r["status"].as_str()) {
        Some("queued") => "queued",
        Some("waiting") => "waiting",
        Some("completed") => "completed",
        Some("failed") => "failed",
        Some("cancelled" | "rolled_back") => "cancelled",
        Some("interrupted") => "interrupted",
        _ => "running",
    }
}

/// TS `taskPrompt`.
fn task_prompt(args: &Args) -> String {
    let task = str_arg(args, "task").unwrap_or_default();
    match str_arg(args, "role") {
        None | Some("general") => task.to_owned(),
        Some(role) => format!("Act as the {role} sub-agent for this task.\n\n{task}"),
    }
}

/// `timeoutMs` of a task wait, within the MCP wait cap.
fn wait_timeout(args: &Args) -> Duration {
    let ms = args
        .get("timeoutMs")
        .and_then(Value::as_f64)
        .map_or(DEFAULT_TASK_WAIT_MS, |ms| {
            (ms.max(1.0) as u64).min(MAX_WAIT_MS)
        });
    Duration::from_millis(ms)
}

/// `delegate_task` with `target.environmentId`: the child runs as an ordinary thread there;
/// this thread keeps the task (`RemoteDelegation.delegate`).
async fn delegate_remote(cx: &Cx<'_>, args: &Args, environment: &str) -> ToolResult {
    let caller = cx.require_thread("delegate_task")?.clone();
    let task_id = crate::remote_tasks::delegate(cx, args, environment, &task_prompt(args)).await?;
    if str_arg(args, "mode") != Some("wait") {
        return read_task(
            cx,
            &caller.thread_id,
            &task_id,
            false,
            Acknowledge::Terminal,
        )
        .await;
    }
    let upgrade = WakeUpgrade::arm(cx, &caller.thread_id, &task_id, &task_id);
    let timed_out =
        crate::remote_tasks::wait_for_result(cx, &caller.thread_id, &task_id, wait_timeout(args))
            .await?;
    let read = read_task(
        cx,
        &caller.thread_id,
        &task_id,
        timed_out,
        Acknowledge::Terminal,
    )
    .await?;
    upgrade.settle(cx, &read).await;
    Ok(read)
}

/// `awaitTask`'s exit (`OrchestratorMcpService.ts:1984`): a blocking wait that ends without
/// returning a terminal result upgrades the task's wake to `always`, so a later result still
/// reaches the parent. Dropped unsettled, as when the call goes away or fails, it upgrades in
/// the background.
struct WakeUpgrade {
    engine: std::sync::Arc<dyn conn_engine::Engine>,
    command: Option<Value>,
}

impl WakeUpgrade {
    fn arm(cx: &Cx<'_>, parent: &str, task_id: &str, command_id: &str) -> Self {
        Self {
            engine: cx.config().engine.clone(),
            command: Some(json!({
                "type": "delegated_task.wake-policy",
                "commandId": format!("{command_id}:wake-always"),
                "parentThreadId": parent,
                "taskId": task_id,
                "completionWake": "always",
            })),
        }
    }

    /// After the read the wait returns: the upgrade runs unless that read is terminal, read
    /// first so a result returned here never also wakes the parent. The guard stays armed until
    /// the upgrade commits, so a call dropped meanwhile still upgrades.
    async fn settle(mut self, cx: &Cx<'_>, read: &Value) {
        if !TERMINAL.contains(&read["status"].as_str().unwrap_or_default())
            && let Some(command) = self.command.clone()
        {
            #[cfg(test)]
            crate::tests::park_at("wake-upgrade").await;
            // Refused only when the task already wakes the parent.
            let _ = cx.dispatch(command).await;
        }
        self.command = None;
    }
}

impl Drop for WakeUpgrade {
    fn drop(&mut self) {
        let Some(command) = self.command.take() else {
            return;
        };
        let (Ok(command), Ok(runtime)) = (
            conn_contract::from_json::<conn_contract::Command>(command),
            tokio::runtime::Handle::try_current(),
        ) else {
            return;
        };
        let engine = self.engine.clone();
        runtime.spawn(async move {
            let _ = engine.dispatch(command).await;
        });
    }
}

pub(super) async fn delegate(cx: &Cx<'_>, args: &Args) -> ToolResult {
    let caller = cx.require_thread("delegate_task")?;
    let target = args.get("target").cloned().unwrap_or(Value::Null);
    if let Some(environment) = target["environmentId"].as_str()
        && environment != cx.config().environment_id
    {
        return delegate_remote(cx, args, environment).await;
    }
    // TS `actsAsCaller`: the calling thread, then `writingCaller`.
    cx.writing_caller().await?;
    let parent = cx.projection(&caller.thread_id).await?;
    let parent_thread = &parent["thread"];
    if let Some(project) = target["projectId"].as_str()
        && parent_thread["projectId"] != project
    {
        return Err(fail(
            "invalid_request",
            "A local task runs in this thread's project. Omit target.projectId, or pass target.environmentId to run it in that environment's project.",
        ));
    }
    let active = view::active_run(&parent)
        .filter(|run| run["providerInstanceId"] == caller.provider_instance_id.as_str());
    if active.is_none() {
        return Err(fail(
            "parent_not_active",
            "Delegated tasks require an active run owned by this MCP provider session.",
        ));
    }
    let key = Cx::request_key(args);
    let command_id = cx.stable_id("command", "delegate-task", &key);
    // TS `isRetryOfAcceptedDelegation`: a retry keeps the checkout and the provider the first
    // call was accepted with, so it skips the project enablement filter, as T3's receipt replay.
    let retried = cx
        .engine()
        .created_run_status(&command_id)
        .await
        .map_err(super::internal)?
        .is_some();
    // T3 `resolveTargetRechecking`, shared with `create_threads`: driver and instance
    // resolution, project enablement, the health check, the model and its options.
    let selection =
        super::create_threads::resolve_target_rechecking(cx, parent_thread, &target, retried)
            .await?;
    let runtime_mode = super::create_threads::runtime_mode_for(
        cx,
        parent_thread,
        &selection,
        str_arg(args, "runtimeMode"),
    )?;
    let interaction_mode = threads::resolve_interaction_mode(
        parent_thread["interactionMode"]
            .as_str()
            .unwrap_or("default"),
        str_arg(args, "interactionMode"),
    )?;

    let parent_run = active.cloned().unwrap_or_default();
    let task_id = format!("{TASK_PREFIX}{command_id}");
    let child = format!("thread:delegated-task:{command_id}");
    let isolated = if str_arg(args, "isolation") == Some("worktree") && !retried {
        Some(worktree_base(cx, parent_thread).await?)
    } else {
        None
    };
    let prompt = task_prompt(args);
    let wait = str_arg(args, "mode") == Some("wait");
    let mut command = json!({
        "type": "delegated_task.request",
        "commandId": command_id,
        "parentThreadId": caller.thread_id,
        "parentRunId": parent_run["id"],
        "parentNodeId": parent_run["rootNodeId"],
        "task": prompt,
        "modelSelection": selection,
        "runtimeMode": runtime_mode,
        "interactionMode": interaction_mode,
        // A wait delivers the result through this call; it wakes the parent only after the
        // wait gives up (below).
        "completionWake": if wait { "settled_only" } else { "always" },
        "createdBy": "agent",
        "creationSource": "mcp",
    });
    if let Some(title) = str_arg(args, "title")
        .map(str::trim)
        .filter(|t| !t.is_empty())
    {
        command["title"] = json!(title);
    }
    if let Some((_, base)) = &isolated {
        command["workspaceStrategy"] =
            json!({"type": "worktree", "baseRef": base, "startFromOrigin": false});
    }
    // A worktree child's setup script runs after the commit, as T3's `prepareRun`: the child's
    // run waits in `preparing` until it ends (`prepare_child`). A fenced parent runs none.
    let preparation = match &isolated {
        Some((project, _)) => {
            let fenced = cx
                .link_origin()
                .await?
                .is_some_and(|origin| crate::peers::link_origin_is_fenced(&origin));
            Some((project.clone(), fenced))
        }
        None => None,
    };
    // The dispatch and the preparation run on their own task, holding the armed upgrade when
    // the call waits, then hand it back. A call dropped meanwhile leaves both to that task, so
    // the child is still prepared and the parent still hears the result.
    let guard = wait.then(|| WakeUpgrade::arm(cx, &caller.thread_id, &task_id, &command_id));
    let service = cx.service.clone();
    let (back, handed) = tokio::sync::oneshot::channel();
    let (prepared_id, prepared_child) = (command_id.clone(), child.clone());
    tokio::spawn(async move {
        let dispatched = super::dispatch_to(service.config.engine.as_ref(), command).await;
        if dispatched.is_ok()
            && let Some((project, fenced)) = preparation
        {
            prepare_child(&service, &prepared_id, &prepared_child, &project, fenced).await;
        }
        let _ = back.send((dispatched, guard));
    });
    let (dispatched, upgrade) = handed
        .await
        .map_err(|_| super::internal("delegate_task: the dispatch ended"))?;
    if let Err(error) = dispatched {
        // No task was made: nothing to upgrade.
        if let Some(mut upgrade) = upgrade {
            upgrade.command = None;
        }
        return Err(error);
    }

    if let Some(upgrade) = upgrade {
        let deadline = tokio::time::Instant::now() + wait_timeout(args);
        let read = match wait_for_task(cx, &caller.thread_id, &child, &task_id, deadline).await? {
            Some(read) => read,
            None => read_task(cx, &caller.thread_id, &task_id, true, Acknowledge::Terminal).await?,
        };
        upgrade.settle(cx, &read).await;
        return Ok(read);
    }
    read_task(
        cx,
        &caller.thread_id,
        &task_id,
        false,
        Acknowledge::Terminal,
    )
    .await
}

/// `waitForTask` (`OrchestratorMcpService.ts:2090`): follows the task until a read of it ends a
/// wait (a result, a question or an approval) and returns that read, or `None` when `deadline`
/// passes first or a stream ends. Both threads are followed from before the first read, so
/// nothing that lands after it is missed.
async fn wait_for_task(
    cx: &Cx<'_>,
    parent: &str,
    child: &str,
    task_id: &str,
    deadline: tokio::time::Instant,
) -> Result<Option<Value>, ToolError> {
    let subscribe = |thread: &str| {
        let thread = thread.to_owned();
        async move {
            let input =
                conn_contract::from_json(json!({"threadId": thread})).map_err(super::internal)?;
            cx.engine().subscribe_thread(input).await.map_err(|_| {
                fail(
                    "thread_not_found",
                    format!("Thread {thread} is no longer available."),
                )
            })
        }
    };
    let mut parent_events = subscribe(parent).await?;
    let mut child_events = subscribe(child).await?;
    let mut read = read_task(cx, parent, task_id, false, Acknowledge::Terminal).await?;
    #[cfg(test)]
    crate::tests::after_first_task_read().await;
    loop {
        if read.get("next").is_none() {
            return Ok(Some(read));
        }
        loop {
            let (item, from_child) = tokio::select! {
                item = parent_events.recv() => (item, false),
                item = child_events.recv() => (item, true),
                () = tokio::time::sleep_until(deadline) => return Ok(None),
            };
            let item = match item {
                None | Some(Err(_)) => return Ok(None),
                Some(Ok(item)) => conn_contract::to_json(&item),
            };
            // `TASK_WAKE_EVENTS`: the parent's row of this task, and the child's work.
            let kind = item["event"]["type"].as_str().unwrap_or_default();
            let wakes = if from_child {
                matches!(
                    kind,
                    "run.updated"
                        | "subagent.updated"
                        | "provider-thread.updated"
                        | "runtime-request.updated"
                )
            } else {
                kind == "subagent.updated" && item["event"]["payload"]["id"] == task_id
            };
            if wakes {
                break;
            }
        }
        read = read_task(cx, parent, task_id, false, Acknowledge::Terminal).await?;
    }
}

/// Whether a read of a finished task acknowledges its result, so no later wake repeats it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Acknowledge {
    /// `readTask(..., acknowledgeTerminal = true)`: `delegate_task`, `task_status`.
    Terminal,
    /// `task_cancel` and a wait in progress only look.
    Never,
}

/// The project and the commit a `worktree` child starts from: the parent checkout's `HEAD`,
/// so the parent's uncommitted edits stay out (TS `delegate`, isolation `worktree`).
async fn worktree_base(cx: &Cx<'_>, parent: &Value) -> Result<(Value, String), ToolError> {
    let project = super::worktree::project(cx, parent).await?;
    let root = project["workspaceRoot"]
        .as_str()
        .unwrap_or_default()
        .to_owned();
    let parent_worktree = parent["worktreePath"].as_str();
    let cwd = parent_worktree.unwrap_or(&root);
    let base = conn_vcs::repo::resolve_commit(Path::new(cwd), "HEAD")
        .await
        .ok()
        .flatten()
        .ok_or_else(|| {
            fail(
                "invalid_request",
                "Unable to resolve the parent checkout commit.",
            )
        })?;
    // The child's worktree is made from the project root, so a parent checkout in another
    // repository would hand it a commit it cannot find.
    if parent_worktree.is_some()
        && conn_vcs::repo::resolve_commit(Path::new(&root), &base)
            .await
            .ok()
            .flatten()
            .is_none()
    {
        return Err(fail(
            "invalid_request",
            format!(
                "Isolation \"worktree\" creates the child checkout in project \"{}\" ({root}), which does not contain the parent checkout's commit. Use isolation \"shared\" to work in the parent's checkout.",
                project["title"].as_str().unwrap_or_default()
            ),
        ));
    }
    Ok((project, base))
}

/// `ThreadLaunchService.prepareRun` for a `worktree` child: the project's
/// `runOnWorktreeCreate` script starts in the child's checkout. The child's run waits in
/// `preparing` until a script marked `async: false` has ended, and fails without starting when
/// that script fails. Any other script overlaps the agent.
async fn prepare_child(
    service: &std::sync::Arc<crate::McpService>,
    command_id: &str,
    child: &str,
    project: &Value,
    fenced: bool,
) {
    let engine = service.config.engine.as_ref();
    let Ok(projection) = engine.get_thread_projection(child.into()).await else {
        return;
    };
    let Some(run_id) = projection["runs"]
        .as_array()
        .and_then(|runs| runs.iter().find(|r| r["status"] == "preparing"))
        .and_then(|run| run["id"].as_str())
        .map(str::to_owned)
    else {
        return;
    };
    let path = projection["thread"]["worktreePath"]
        .as_str()
        .unwrap_or_default();
    let config = service.config.worktrees.as_ref();
    // `skipped-for-link`: a link below full access runs none of the user's own code.
    let started = match config {
        Some(config) if !path.is_empty() && !fenced => super::worktree::start_project_script(
            config,
            child,
            project,
            path,
            super::worktree::ScriptTrigger::Setup,
            Some(super::worktree::Observe::default()),
        )
        .await
        .map(Some),
        _ => Ok(None),
    };
    let terminals = config.and_then(|config| config.terminals.clone());
    let service = service.clone();
    let (command_id, child) = (command_id.to_owned(), child.to_owned());
    let settle = async move {
        // No script, or an async one: it overlaps the agent.
        let held = started.map(|run| {
            run.filter(|run| !run.is_async)
                .and_then(|run| Some((run.started, run.completion?)))
        });
        let outcome = match held {
            Err(error) => Err(error),
            Ok(None) => Ok(()),
            Ok(Some((status, completion))) => {
                let engine = service.config.engine.as_ref();
                tokio::select! {
                    code = completion => match code.ok().flatten() {
                        Some(0) => Ok(()),
                        code => Err(format!(
                            "Setup script exited with {}.",
                            code.map_or("no exit code".to_owned(), |c| c.to_string())
                        )),
                    },
                    () = left_preparing(engine, &child, &run_id) => {
                        // A cancel stops the script too (T3 closes the setup terminal).
                        if let (Some(terminals), Some(terminal)) =
                            (&terminals, status["terminalId"].as_str())
                            && let Ok(input) = conn_contract::from_json(json!({
                                "threadId": child, "terminalId": terminal, "deleteHistory": true}))
                        {
                            terminals.close(input);
                        }
                        return;
                    }
                }
            }
        };
        let command = match outcome {
            Ok(()) => {
                json!({"type": "prepared-run.release", "commandId": format!("{command_id}:release"),
                "threadId": child, "runId": run_id})
            }
            Err(message) => {
                json!({"type": "prepared-run.fail", "commandId": format!("{command_id}:fail"),
                "threadId": child, "runId": run_id,
                "failure": {"class": "validation_error", "message": message, "code": null, "retryable": false}})
            }
        };
        if let Ok(command) = conn_contract::from_json(command)
            && let Err(error) = service.config.engine.dispatch(command).await
        {
            eprintln!("delegate_task preparation for {child}: {error:?}");
        }
    };
    // T3 schedules the preparation: the call returns while the child waits in `preparing`.
    tokio::spawn(settle);
}

/// Resolves once `run_id` is no longer `preparing`: a cancel or stop ended it before its
/// setup did. Never resolves when the thread cannot be watched.
async fn left_preparing(engine: &dyn conn_engine::Engine, thread: &str, run_id: &str) {
    let preparing = || async {
        engine
            .get_thread_projection(thread.into())
            .await
            .ok()
            .and_then(|p| {
                p["runs"]
                    .as_array()?
                    .iter()
                    .find(|run| run["id"] == run_id)
                    .map(|run| run["status"] == "preparing")
            })
            .unwrap_or(false)
    };
    let Ok(input) = conn_contract::from_json(json!({"threadId": thread})) else {
        return std::future::pending().await;
    };
    let Ok(mut stream) = engine.subscribe_thread(input).await else {
        return std::future::pending().await;
    };
    while preparing().await {
        if stream.recv().await.is_none() {
            return std::future::pending().await;
        }
    }
}

pub(super) async fn status(cx: &Cx<'_>, args: &Args) -> ToolResult {
    let caller = cx.require_thread("task_status")?;
    // TS `actsAsCaller`: the calling thread, then `writingCaller`.
    cx.writing_caller().await?;
    read_task(
        cx,
        &caller.thread_id,
        str_arg(args, "taskId").unwrap_or_default(),
        false,
        Acknowledge::Terminal,
    )
    .await
}

pub(super) async fn cancel(cx: &Cx<'_>, args: &Args) -> ToolResult {
    let caller = cx.require_thread("task_cancel")?;
    // TS `actsAsCaller`: the calling thread, then `writingCaller`.
    cx.writing_caller().await?;
    let task_id = str_arg(args, "taskId").unwrap_or_default();
    // The task runs in a linked environment: its thread there is stopped through the link.
    if let Some(row) = remote_row(cx, &caller.thread_id, task_id).await? {
        return crate::remote_tasks::cancel(cx, &caller.thread_id, &row, args).await;
    }
    let current = read_task(cx, &caller.thread_id, task_id, false, Acknowledge::Never).await?;
    if TERMINAL.contains(&current["status"].as_str().unwrap_or_default()) {
        return Ok(json!({"taskId": task_id, "status": current["status"]}));
    }
    let child_id = current["childThreadId"]
        .as_str()
        .unwrap_or_default()
        .to_owned();
    let child = cx.projection(&child_id).await?;
    let waiting = current["workState"] == "waiting_for_children";
    let running = view::active_run(&child).is_some();
    if !waiting && !running && task_queued_runs(&child, task_id, &current).is_empty() {
        return Err(fail(
            "task_not_cancellable",
            format!("Delegated task {task_id} has no interruptible child run."),
        ));
    }
    // Cancelling writes to the child and every thread under it; their user may have raised
    // one above the parent's modes since it was delegated. All are checked before anything
    // changes, and again in the engine's write (`OrchestratorMcpService.ts:2866`).
    let parent = cx.projection(&caller.thread_id).await?;
    let limit = json!({
        "runtimeMode": parent["thread"]["runtimeMode"].as_str().unwrap_or("approval-required"),
        "interactionMode": parent["thread"]["interactionMode"].as_str().unwrap_or("default"),
    });
    assert_stoppable(cx, &limit, &child_id).await?;
    let key = Cx::request_key(args);
    let reason = str_arg(args, "reason").unwrap_or("Cancelled by its parent agent.");
    // A task waiting for children has no turn to stop; the Stop still reaches its delegates and
    // the background work it awaits (`OrchestratorMcpService.ts:3026`).
    let cancelled = cx
        .engine()
        .cancel_delegated_task(json!({
            "commandId": cx.stable_id("command", "task-cancel", &key),
            "threadId": child_id,
            "parentThreadId": caller.thread_id,
            "taskId": task_id,
            "reason": reason,
            "modeLimit": limit,
        }))
        .await;
    match cancelled {
        Ok(()) => {}
        Err(conn_engine::EngineError::Rejected(error)) => {
            let message = error["message"].as_str().unwrap_or_default();
            return Err(match error["code"].as_str() {
                Some("runtime_mode_escalation_denied") => {
                    fail("runtime_mode_escalation_denied", message)
                }
                Some("interaction_mode_escalation_denied") => {
                    fail("interaction_mode_escalation_denied", message)
                }
                _ => fail(
                    "task_not_cancellable",
                    format!("Unable to stop delegated task {task_id}: {message}"),
                ),
            });
        }
        Err(conn_engine::EngineError::Internal(message)) => return Err(super::internal(message)),
    }
    // Its result no longer wakes the parent; disposed before its queued turns are cancelled,
    // so a follow-up that ends with them stays quiet.
    if let Err(error) = cx
        .dispatch(json!({
            "type": "delegated_task.completion-delivery.dispose",
            "commandId": cx.stable_id("command", "cancel-task-completion-delivery", &key),
            "parentThreadId": caller.thread_id,
            "taskId": task_id,
        }))
        .await
    {
        eprintln!("task_cancel could not dispose the delivery of {task_id}: {error:?}");
    }
    // Stop keeps the queue for Resume, so cancelling the task removes its queued turns, read
    // after the Stop.
    let child = cx.projection(&child_id).await?;
    for run in task_queued_runs(&child, task_id, &current) {
        cx.dispatch(json!({
            "type": "queued-run.cancel",
            "commandId": cx.stable_id("command", &format!("cancel-task-queued-run:{run}"), &key),
            "threadId": child_id,
            "runId": run,
        }))
        .await?;
    }
    Ok(json!({"taskId": task_id, "status": "cancel_requested"}))
}

/// `assertStoppable`: `thread` and every app-owned task thread under it run within `limit`.
async fn assert_stoppable(cx: &Cx<'_>, limit: &Value, thread: &str) -> Result<(), ToolError> {
    let limits = super::Limits {
        runtime_mode: limit["runtimeMode"].as_str().unwrap_or_default().to_owned(),
        interaction_mode: limit["interactionMode"]
            .as_str()
            .unwrap_or_default()
            .to_owned(),
    };
    let mut pending = vec![thread.to_owned()];
    let mut seen: Vec<String> = vec![];
    while let Some(thread) = pending.pop() {
        if seen.contains(&thread) {
            continue;
        }
        let projection = match cx.projection(&thread).await {
            Ok(projection) => projection,
            Err(ToolError::Failure {
                code: "thread_not_found",
                ..
            }) => continue,
            Err(other) => return Err(other),
        };
        if projection["thread"]["deletedAt"].is_null() {
            cx.within_limits(&limits, &projection["thread"])?;
        }
        pending.extend(
            projection["subagents"]
                .as_array()
                .into_iter()
                .flatten()
                .filter(|row| row["origin"] == "app_owned")
                .filter_map(|row| row["childThreadId"].as_str().map(str::to_owned)),
        );
        seen.push(thread);
    }
    Ok(())
}

/// The task's own queued turns in its child (`OrchestratorMcpService.ts:2947`).
fn task_queued_runs(child: &Value, task_id: &str, current: &Value) -> Vec<String> {
    child["runs"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|run| {
            run["status"] == "queued"
                && (run["delegatedTaskId"] == task_id || run["id"] == current["childRunId"])
        })
        .filter_map(|run| run["id"].as_str().map(str::to_owned))
        .collect()
}

/// The parent's row of `task_id` when the task runs in a linked environment.
async fn remote_row(cx: &Cx<'_>, parent: &str, task_id: &str) -> Result<Option<Value>, ToolError> {
    let projection = cx.projection(parent).await?;
    Ok(projection["subagents"]
        .as_array()
        .and_then(|rows| {
            rows.iter().find(|row| {
                row["id"] == task_id
                    && row["origin"] == "app_owned"
                    && crate::remote_tasks::is_remote(row)
            })
        })
        .cloned())
}

/// `OrchestratorMcpDelegateTaskResult` for a task of `parent` (`readTask`,
/// `OrchestratorMcpService.ts:1703`). A task is the parent's row, so a follow-up in the same
/// child is its own task: it reads only the runs bound to it (`delegatedTaskId`), and the
/// original reads the rest.
async fn read_task(
    cx: &Cx<'_>,
    parent: &str,
    task_id: &str,
    wait_timed_out: bool,
    acknowledge: Acknowledge,
) -> ToolResult {
    let parent_projection = cx.projection(parent).await?;
    if let Some(row) = remote_row(cx, parent, task_id).await? {
        return crate::remote_tasks::read_task(cx, &parent_projection, &row, wait_timed_out, true)
            .await;
    }
    let not_found = || {
        fail(
            "task_not_found",
            format!("Delegated task {task_id} does not belong to thread {parent}."),
        )
    };
    let row = parent_projection["subagents"]
        .as_array()
        .and_then(|rows| {
            rows.iter()
                .find(|r| r["id"] == task_id && r["origin"] == "app_owned")
        })
        .filter(|row| row["childThreadId"].is_string())
        .cloned()
        .ok_or_else(not_found)?;
    let child_id = row["childThreadId"].as_str().unwrap_or_default().to_owned();
    let child = cx.projection(&child_id).await.map_err(|_| not_found())?;
    if child["thread"]["lineage"]["parentThreadId"] != parent {
        return Err(not_found());
    }
    let original = child["thread"]["forkedFrom"]["nodeId"] == task_id;
    // A turn that only answers a monitor update is no task's work (`delegatedTaskProgress`).
    let monitor =
        conn_engine::monitor_runs(child["messages"].as_array().map_or(&[], Vec::as_slice));
    let mut runs: Vec<&Value> = child["runs"]
        .as_array()
        .map(|r| {
            r.iter()
                .filter(|run| match run["delegatedTaskId"].as_str() {
                    Some(task) => task == task_id,
                    None => original,
                })
                .filter(|run| !monitor.contains(&run["id"]))
                .collect()
        })
        .unwrap_or_default();
    runs.sort_by_key(|run| run["ordinal"].as_u64().unwrap_or(0));
    let first = runs.first().copied();
    let latest = runs.last().copied();
    // The engine publishes the row once the task's work settled (`finalizeAppOwnedSubagent`).
    let published = !row["completedAt"].is_null()
        && TERMINAL.contains(&row["status"].as_str().unwrap_or_default());
    let active = runs
        .iter()
        .any(|run| view::is_live(run) && !(run["status"] == "queued" && run["queueHeld"] == true));
    let ran = runs.iter().any(|run| !view::is_live(run));
    let (status, work_state) = if published {
        (task_status(Some(&row)), "result_available")
    } else if !active && ran {
        // `delegatedTaskProgress`: its turns ended, its children have not.
        ("running", "waiting_for_children")
    } else {
        match task_status(latest) {
            s @ "queued" => (s, "working"),
            _ => ("running", "working"),
        }
    };
    let terminal = TERMINAL.contains(&status);
    let terminal_run = runs.iter().rev().find(|run| !view::is_live(run)).copied();
    // `readTask`: the result the task was published with (`OrchestratorMcpService.ts:1819`);
    // a later run in the same child never replaces it. A row published before rows kept their
    // result reads it from its own last run.
    let summary = match (terminal, &row["result"]) {
        (false, _) => Value::Null,
        (true, Value::Null) => json!(terminal_run.map_or_else(
            || "Child task completed without an assistant result.".to_owned(),
            |run| conn_engine::delegated_task_result(&child, run),
        )),
        (true, result) => result.clone(),
    };
    let requests: Vec<&Value> = child["runtimeRequests"]
        .as_array()
        .map(|r| r.iter().filter(|r| r["status"] == "pending").collect())
        .unwrap_or_default();
    let has_question = !terminal && requests.iter().any(|r| r["kind"] == "user_input");
    let approval = (!terminal)
        .then(|| requests.iter().find(|r| r["kind"] != "user_input"))
        .flatten()
        .map(|request| {
            let run_id = child["turnItems"]
                .as_array()
                .and_then(|items| items.iter().find(|i| i["requestId"] == request["id"]))
                .map_or_else(
                    || latest.map_or(Value::Null, |r| r["id"].clone()),
                    |i| i["runId"].clone(),
                );
            json!({"requestId": request["id"], "kind": request["kind"], "runId": run_id})
        });
    let selection = latest.map_or(&child["thread"]["modelSelection"], |r| &r["modelSelection"]);
    let title = child["thread"]["title"].as_str().unwrap_or_default();
    let pending_runs = child["runs"].as_array().is_some_and(|all| {
        all.iter().any(|r| {
            view::is_live(r)
                && !(r["status"] == "queued" && r["queueHeld"] == true)
                && r["ordinal"].as_u64() > first.and_then(|f| f["ordinal"].as_u64())
        })
    });
    let ends_wait = terminal || has_question || approval.is_some();
    let mut result = json!({
        "taskId": task_id,
        "childThreadId": child_id,
        "remoteChild": null,
        "link": crate::links::thread_link(
            cx.config(),
            &Caller::Thread(crate::ThreadCaller {
                thread_id: parent.to_owned(),
                provider_session_id: String::new(),
                provider_instance_id: String::new(),
                subagent: false,
                preview: true,
                device: false,
            }),
            &child_id,
            title,
        ),
        "childRunId": first.map_or(Value::Null, |r| r["id"].clone()),
        "childNodeId": task_id,
        "status": status,
        "workState": work_state,
        "hasPendingChildRuns": pending_runs,
        "latestTerminalRunId": terminal_run.map_or(Value::Null, |r| r["id"].clone()),
        "latestTerminalStatus": terminal_run
            .map(|r| task_status(Some(r)))
            .filter(|s| TERMINAL.contains(s)),
        "latestTerminalSummary": null,
        "latestTerminalResultContextTransferId": null,
        "providerInstanceId": selection["instanceId"],
        "model": selection["model"],
        "executedModel": latest.map_or(Value::Null, |r| view::executed_model(&child, r)),
        "options": selection.get("options").cloned().unwrap_or(json!([])),
        "summary": summary,
        "resultContextTransferId": null,
        "hasPendingQuestion": has_question,
        "pendingApproval": approval,
        "waitTimedOut": wait_timed_out,
    });
    if !ends_wait {
        result["next"] = json!(RUNNING_TASK_NEXT);
    }
    if acknowledge == Acknowledge::Terminal && terminal {
        acknowledge_result(cx, &parent_projection, &row).await?;
    }
    Ok(result)
}

/// `delegated_task.completion-delivery.acknowledge` for a result this read returned, observed
/// by the caller's active run (`OrchestratorMcpService.ts:1902`), unless it was already taken.
async fn acknowledge_result(cx: &Cx<'_>, parent: &Value, row: &Value) -> Result<(), ToolError> {
    let Caller::Thread(caller) = cx.caller else {
        return Ok(());
    };
    if matches!(
        row["completionDelivery"]["state"].as_str(),
        Some("acknowledged" | "disposed" | "delivered")
    ) {
        return Ok(());
    }
    cx.dispatch(json!({
        "type": "delegated_task.completion-delivery.acknowledge",
        "commandId": cx.stable_id("command", "task-status-acknowledge", &conn_support::uuid_v4()),
        "parentThreadId": caller.thread_id,
        "taskId": row["id"],
        "observedByRunId": observing_run(parent, caller),
    }))
    .await
    .map(|_| ())
}

/// The caller's turn that observed a result it read (`latestActiveRun`): its newest live turn,
/// never one queued behind it, which has not run and observed nothing.
pub(crate) fn observing_run(parent: &Value, caller: &crate::ThreadCaller) -> Value {
    parent["runs"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|run| {
            view::is_live(run)
                && run["status"] != "queued"
                && run["providerInstanceId"] == caller.provider_instance_id.as_str()
        })
        .max_by_key(|run| run["ordinal"].as_u64().unwrap_or(0))
        .map_or(Value::Null, |run| run["id"].clone())
}
