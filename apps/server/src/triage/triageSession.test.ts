import * as NodeCrypto from "@effect/platform-node/NodeCrypto";
import * as NodeServices from "@effect/platform-node/NodeServices";
import { assert, it } from "@effect/vitest";
import { TRIAGE_PROMPT_FILE_NAME } from "@t3tools/contracts";
import * as HostProcess from "@t3tools/shared/HostProcess";
import * as NetService from "@t3tools/shared/Net";
import * as ConfigProvider from "effect/ConfigProvider";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Layer from "effect/Layer";
import * as Path from "effect/Path";
import * as TestConsole from "effect/testing/TestConsole";
import { Command } from "effect/cli";

import packageJson from "../../package.json" with { type: "json" };
import { cli } from "../binCli.ts";
import {
  makePersistedServerRuntimeState,
  persistServerRuntimeState,
} from "../serverRuntimeState.ts";
import { describeServerProcess } from "./triageSession.ts";

it.effect.each(["triage", "unfuck"] as const)(
  "%s works without an agent or running server and leaves existing data unchanged",
  (command) =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const home = yield* fs.makeTempDirectoryScoped({ prefix: "t3-support-" });
      const stateDir = path.join(home, "userdata");
      yield* fs.makeDirectory(stateDir);
      const database = path.join(stateDir, "statev2.sqlite");
      const settings = path.join(stateDir, "settings.json");
      yield* fs.writeFileString(database, "existing database");
      yield* fs.writeFileString(settings, '{"theme":"dark"}');

      const output = yield* Command.runWith(cli, { version: "0.0.0" })([
        command,
        "--base-dir",
        home,
      ]).pipe(
        Effect.andThen(TestConsole.logLines),
        Effect.map((lines) => lines.join("\n")),
        Effect.provideService(HostProcess.Environment, { PATH: "" }),
        Effect.provide(
          Layer.mergeAll(
            NetService.layer,
            ConfigProvider.layer(ConfigProvider.fromEnv({ env: {} })),
            Layer.fresh(TestConsole.layer),
          ),
        ),
      );
      const runs = yield* fs.readDirectory(path.join(stateDir, command));
      assert.lengthOf(runs, 1);
      const scratch = path.join(stateDir, command, runs[0]!);
      const prompt = yield* fs.readFileString(path.join(scratch, TRIAGE_PROMPT_FILE_NAME));
      const context = yield* fs.readFileString(path.join(scratch, "context.md"));
      assert.include(output, path.join(scratch, TRIAGE_PROMPT_FILE_NAME));
      assert.include(context, `Generated by \`t3 ${command}\``);
      assert.include(context, "not running (no server-runtime.json");
      assert.include(prompt, path.join(scratch, "context.md"));
      assert.include(prompt, command === "unfuck" ? "recovery playbook" : "triage playbook");
      if (command === "unfuck") {
        assert.include(output, "Updating the npx CLI does not update the desktop app.");
      }
      assert.equal(yield* fs.readFileString(database), "existing database");
      assert.equal(yield* fs.readFileString(settings), '{"theme":"dark"}');
      assert.isFalse(yield* fs.exists(path.join(stateDir, "server-runtime.json")));
    }).pipe(Effect.provide(Layer.mergeAll(NodeServices.layer, NodeCrypto.layer))),
);

it.effect("reports the version the running server recorded, not the CLI's", () =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const statePath = path.join(
      yield* fs.makeTempDirectoryScoped({ prefix: "t3-triage-" }),
      "server-runtime.json",
    );
    const state = yield* makePersistedServerRuntimeState({
      config: { host: undefined, devUrl: undefined },
      port: 3773,
    });
    yield* persistServerRuntimeState({ path: statePath, state });

    assert.equal(
      yield* describeServerProcess(statePath),
      `running (pid ${String(process.pid)}, http://127.0.0.1:3773, version ${packageJson.version})`,
    );
  }).pipe(Effect.provide(NodeServices.layer)),
);
