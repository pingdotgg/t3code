/**
 * KiroAdapter — Kiro CLI (`kiro-cli acp`) over ACP.
 *
 * Modelled on {@link ./GrokAdapter}: the shared `AcpSessionRuntime` owns the
 * transport and `KiroAcpSupport` owns every Kiro-specific decision, leaving
 * this module to translate ACP session updates into orchestration events and
 * to keep turn bookkeeping honest under steering, interrupts, and restarts.
 *
 * Kiro-specific behaviour, all observed against kiro-cli 2.16.2:
 *   - reasoning arrives as `agent_thought_chunk` and is published on the
 *     reasoning stream rather than as assistant text;
 *   - permission option ids are snake_case, so options are matched by ACP
 *     `kind`. `full-access` threads auto-approve from the advertised options;
 *     every other runtime mode asks, because Kiro exposes no notion of
 *     "routine vs risky" over ACP for `auto`/`auto-accept-edits` to use;
 *   - `session/set_model` works mid-session, so model switches do not need a
 *     new thread;
 *   - Kiro's ACP "modes" are agent configurations (`kiro_default`,
 *     `kiro_planner`, every custom agent), not interaction modes. They are
 *     therefore configured per instance via the `agent` setting instead of
 *     being mapped onto T3 Code's plan/implement modes, which would promise
 *     restrictions Kiro is not applying;
 *   - clarifying questions arrive as assistant text: Kiro never sends
 *     `elicitation/create`, even when the client advertises both elicitation
 *     modes, so there is no structured user-input path.
 *
 * @module KiroAdapter
 */
