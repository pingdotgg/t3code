import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const dir = process.env.T3_PEBBLE_INSTALL_DIR!;
const state = process.env.T3_PEBBLE_INSTALL_STATE!;
const ip = process.env.T3_PEBBLE_INSTALL_IP!;
const domain = process.env.T3_PEBBLE_INSTALL_DOMAIN!;
const bun = Bun.which("bun");
if (!dir || !state || !ip || !domain || !bun) throw new Error("Missing installer settings");
const label = "codes.t3.pebble-companion";
const path = join(process.env.HOME!, "Library", "LaunchAgents", `${label}.plist`);
const xml = (value: string) => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&apos;");
const entry = (key: string, value: string) => `<key>${xml(key)}</key><string>${xml(value)}</string>`;
const environment = { PATH: `${bun.slice(0, bun.lastIndexOf("/"))}:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin`, T3_PEBBLE_INSTALL_STATE: state, T3_PEBBLE_INSTALL_DOMAIN: domain, T3_PEBBLE_HOST: ip, T3_PEBBLE_CERT: join(dir, ".tls/cert.pem"), T3_PEBBLE_KEY: join(dir, ".tls/key.pem") };
const plist = `<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0"><dict>${entry("Label", label)}<key>ProgramArguments</key><array><string>${xml(join(dir, "service-run.sh"))}</string></array><key>EnvironmentVariables</key><dict>${Object.entries(environment).map(([k,v]) => entry(k,v)).join("")}</dict><key>RunAtLoad</key><true/><key>KeepAlive</key><true/><key>ThrottleInterval</key><integer>30</integer></dict></plist>`;
await mkdir(join(process.env.HOME!, "Library", "LaunchAgents"), { recursive: true });
const target = `gui/${process.getuid!()}`;
const existing = Bun.spawnSync(["launchctl", "print", `${target}/${label}`], { stdout: "ignore", stderr: "ignore" });
if (existing.success) throw new Error(`The ${label} service is already installed. Remove it before reinstalling.`);
await writeFile(path, plist, { mode: 0o600, flag: "wx" });
const result = Bun.spawnSync(["launchctl", "bootstrap", target, path], { stderr: "inherit" });
if (!result.success) throw new Error(`Could not start the companion. Remove ${path} before retrying.`);
