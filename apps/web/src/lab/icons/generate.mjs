// Regenerates iconSet.generated.ts from the Heroicons-format concept assets.
//   node src/lab/icons/generate.mjs [assetsDir]
// Default assetsDir: /Users/nckrtl/apps/superheroicons/consumers/conn/final
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const assets = process.argv[2] ?? "/Users/nckrtl/apps/superheroicons/consumers/conn/final";
const out = join(dirname(fileURLToPath(import.meta.url)), "iconSet.generated.ts");
const manifest = JSON.parse(readFileSync(join(assets, "manifest.json"), "utf8"));

// Variant order is the tuple order in the generated file: outline24, solid24, solid20, solid16.
const variants = [
  ["24/outline", "0 0 24 24"],
  ["24/solid", "0 0 24 24"],
  ["20/solid", "0 0 20 20"],
  ["16/solid", "0 0 16 16"],
];

const inner = (file, viewBox) => {
  const svg = readFileSync(file, "utf8");
  if (!svg.includes(`viewBox="${viewBox}"`))
    throw new Error(`${file}: expected viewBox ${viewBox}`);
  if (viewBox === "0 0 24 24" && file.includes("outline") && !svg.includes('stroke-width="1.5"')) {
    throw new Error(`${file}: expected stroke-width 1.5 on the root`);
  }
  const body = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>"));
  return body.replace(/\s*\n\s*/g, "").trim();
};

const concepts = readdirSync(join(assets, "24/outline"))
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.slice(0, -4))
  .sort();

const lines = [];
for (const id of concepts) {
  const tuple = variants.map(([dir, vb]) =>
    JSON.stringify(inner(join(assets, dir, `${id}.svg`), vb)),
  );
  lines.push(`  ${JSON.stringify(id)}: [${tuple.join(", ")}],`);
}

// Keys drop dashes and case so Lucide's PascalCase names and connIcon's kebab names meet.
const normalize = (name) => name.replace(/-/g, "").toLowerCase();
const map = {};
for (const [lucide, concept] of Object.entries(manifest.lucide)) {
  if (!concepts.includes(concept)) throw new Error(`${lucide} maps to unknown concept ${concept}`);
  const key = normalize(lucide);
  if (map[key] && map[key] !== concept) throw new Error(`name clash on ${key}`);
  map[key] = concept;
}
const mapLines = Object.keys(map)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`);

writeFileSync(
  out,
  `// @generated by generate.mjs from ${assets}. Do not edit.
// Lab only: the icon switch in src/lab/icons.

/** Inner SVG markup per concept: [outline 24, solid 24, solid 20, solid 16]. */
export const CONCEPT_MARKUP: Record<string, readonly [string, string, string, string]> = {
${lines.join("\n")}
};

/** Lucide name, lowercase without dashes, to concept id. */
export const LUCIDE_TO_CONCEPT: Record<string, string> = {
${mapLines.join("\n")}
};
`,
);
console.log(`${concepts.length} concepts, ${mapLines.length} Lucide names -> ${out}`);
