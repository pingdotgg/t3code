export type TranslationKey = keyof (typeof messages)["en"];

export function translate(language: DisplayLanguage, key: TranslationKey): string {
  return messages[language][key];
}

export function useTranslation() {
  const language = useClientSettings((settings) => settings.displayLanguage);
  return { language, t: (key: TranslationKey) => translate(language, key) };
}
