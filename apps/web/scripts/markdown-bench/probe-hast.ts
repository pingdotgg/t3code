import * as NodeFs from "node:fs";
import * as NodePath from "node:path";
import remarkParse from "remark-parse";
import remarkRehype from "remark-rehype";
import { unified } from "unified";
import { VFile } from "vfile";
import { CHAT_MARKDOWN_REHYPE_PLUGINS, CHAT_MARKDOWN_REMARK_PLUGINS } from "@t3tools/shared/markdownPipeline";
import { rehypeHeadingIds } from "../../src/components/chat/markdownFragments";
import { remarkParseWithoutUnusedSyntax } from "../../src/components/chat/markdownSyntaxGates";
import { rehypeTextDirection } from "../../src/components/chat/markdownTextDirection";
import { chatRenderHast } from "../../src/markdown/chatHast";
import { remarkFastParse } from "../../src/markdown/remarkFastParse";
const [, , , file, index] = process.argv;
const text = file === "text" ? index! : JSON.parse(NodeFs.readFileSync(NodePath.join(process.env.HOME ?? "", "bench-work/md-bench/corpus", file!), "utf8"))[Number(index)];
const remark = unified().use(remarkParse).use(remarkParseWithoutUnusedSyntax).use(remarkFastParse).use(CHAT_MARKDOWN_REMARK_PLUGINS).freeze();
const rehype = unified().use(remarkRehype, { allowDangerousHtml: true }).use([...CHAT_MARKDOWN_REHYPE_PLUGINS, rehypeHeadingIds, rehypeTextDirection]).freeze();
const f = new VFile(text);
const mdast = remark.runSync(remark.parse(f), f);
const show = (n: any, d = 0): string => n.type === "text" ? `${" ".repeat(d)}${JSON.stringify(n.value).slice(0, 60)}${n.position ? "" : " (no pos)"}\n` : n.type === "element" || n.type === "root" ? `${" ".repeat(d)}<${n.tagName ?? "root"}>${n.position ? "" : " (no pos)"}\n${(n.children ?? []).map((c: any) => show(c, d + 1)).join("")}` : `${" ".repeat(d)}[${n.type}]\n`;
