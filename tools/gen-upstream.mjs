#!/usr/bin/env node
// Generates the small tables the Conn Server copies from the T3 server, so that a Conn bump
// rewrites them and never needs a hand edit. `--check` fails when a file is stale.
//
//   CONN_MONOREPO=<conn checkout> node tools/gen-upstream.mjs [--check]
//
// Writes:
// - crates/conn-server/src/scopes/generated.rs: the scope of every RPC method
//   (`RPC_REQUIRED_SCOPES` in apps/server/src/auth/RpcAuthorization.ts, which spreads
//   `CLIENT_GUARDED_RPC_SCOPES` from packages/contracts/src/clientRpcPermissions.ts), the
//   methods whose scope depends on the payload, and the settings keys that need
//   `providers:manage`. The payload rules themselves stay by hand in scopes.rs; a test there
//   fails when this list and the hand rules differ.
// - tools/upkeep/http-routes.json: every (method, path) of the T3 server's HTTP API
//   (`EnvironmentHttpApi` in packages/contracts/src/environmentHttp.ts), by reflection.
//   tools/bump-report.mjs compares it with the routes this server serves.
// - crates/conn-contract/src/upstream.rs: `T3_SERVER_VERSION`, the `version` of
//   apps/server/package.json. Clients compare it with their own; the Codex provider sends it
//   as its client version. Every crate reads it as `conn_contract::T3_SERVER_VERSION`.
// - crates/conn-server/src/settings/generated.rs: the settings fields that hold a secret, per
//   group, as apps/server/src/settingsSecrets.ts finds them with `secretSettingsFields`
//   (provider configs by driver, source control hosts by kind, usage limit sources, text
//   generators, cloud speech, EAS and Simlock device hosts), and the secret provider kinds
//   this server knows, and the keys of a `projectSettingsOverrides` entry. settings.rs redacts
//   and restores exactly these secrets.
//
// - crates/conn-server/src/text_generation/generated.rs: the thread title prompts of
//   `buildThreadTitlePrompt` (packages/provider-core), as text parts around their values.
//
// Prints notes for what it cannot generate: scope checks that sit inside a handler
// (`requiredScopeFor*` functions), which the hand code must follow.
