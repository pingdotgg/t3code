// The tags a function body names through `WS_METHODS.x` or `ORCHESTRATION_V2_WS_METHODS.x`.
const constants = { WS_METHODS: rpc.WS_METHODS, ORCHESTRATION_V2_WS_METHODS: orchestration.ORCHESTRATION_V2_WS_METHODS };
function functionBody(file, name) {
  const text = NodeFS.readFileSync(inMonorepo(file), "utf8");
  const start = text.search(new RegExp(`(?:function|const)\\s+${name}\\b`));
  if (start === -1) throw new Error(`${name} not found in ${file}`);
  // The body ends at the first line that closes a top-level block.
  const end = text.indexOf("\n}", start);
  return text.slice(start, end === -1 ? undefined : end);
}
function namedTags(file, name) {
  const tags = new Set();
  for (const match of functionBody(file, name).matchAll(/\b(WS_METHODS|ORCHESTRATION_V2_WS_METHODS)\.(\w+)/g)) {
    const tag = constants[match[1]][match[2]];
    if (typeof tag !== "string") throw new Error(`${match[0]} in ${name} is not a method`);
    tags.add(tag);
  }
  return tags;
}
