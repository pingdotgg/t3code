#!/usr/bin/env node
// Generates the small tables the Conn Server copies from the T3 server, so that a Conn bump
// rewrites them and never needs a hand edit. `--check` fails when a file is stale.
//
//   CONN_MONOREPO=<conn checkout> node tools/gen-upstream.mjs [--check]
//
// Writes:
// - crates/conn-server/src/scopes/generated.rs: the scope of every RPC method
//   (`RPC_REQUIRED_SCOPES` in apps/server/src/auth/RpcAuthorization.ts, which spreads
//   `CLIENT_GUARDED_RPC_SCOPES` from packages/contracts/src/clientRpcPermissions.ts), the
//   methods whose scope depends on the payload, and the settings keys that need
//   `providers:manage`. The payload rules themselves stay by hand in scopes.rs; a test there
//   fails when this list and the hand rules differ.
//
// Prints notes for what it cannot generate: scope checks that sit inside a handler
// (`requiredScopeFor*` functions), which the hand code must follow.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import { importSource, inMonorepo, repoRoot } from "./monorepo.mjs";

const check = process.argv.includes("--check");
const HEADER = [
  "// @generated by tools/gen-upstream.mjs from the Conn monorepo. Do not edit.",
  "// Regenerate: CONN_MONOREPO=<conn checkout> node tools/gen-upstream.mjs",
];

const rustfmt = (code) =>
  NodeChildProcess.execFileSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
    input: code,
    encoding: "utf8",
  });
const str = (value) => JSON.stringify(value);

// ---- Scopes ----------------------------------------------------------------------------

const AUTH_FILE = "apps/server/src/auth/RpcAuthorization.ts";
const CLIENT_FILE = "packages/contracts/src/clientRpcPermissions.ts";
const auth = await importSource(AUTH_FILE);
const client = await importSource(CLIENT_FILE);
const rpc = await importSource("packages/contracts/src/rpc.ts");
const orchestration = await importSource("packages/contracts/src/orchestrationV2.ts");
const settings = await importSource("packages/contracts/src/settings.ts");

const scopes = Object.entries(auth.RPC_REQUIRED_SCOPES)
  .map(([tag, scope]) => [tag, scope])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
for (const [tag, scope] of scopes) {
  if (typeof scope !== "string") throw new Error(`scope of ${tag} is not a string`);
}

// The tags a function body names through `WS_METHODS.x` or `ORCHESTRATION_V2_WS_METHODS.x`.
const constants = { WS_METHODS: rpc.WS_METHODS, ORCHESTRATION_V2_WS_METHODS: orchestration.ORCHESTRATION_V2_WS_METHODS };
function functionBody(file, name) {
  const text = NodeFS.readFileSync(inMonorepo(file), "utf8");
  const start = text.search(new RegExp(`(?:function|const)\\s+${name}\\b`));
  if (start === -1) throw new Error(`${name} not found in ${file}`);
  // The body ends at the first line that closes a top-level block.
  const end = text.indexOf("\n}", start);
  return text.slice(start, end === -1 ? undefined : end);
}
function namedTags(file, name) {
  const tags = new Set();
  for (const match of functionBody(file, name).matchAll(/\b(WS_METHODS|ORCHESTRATION_V2_WS_METHODS)\.(\w+)/g)) {
    const tag = constants[match[1]][match[2]];
    if (typeof tag !== "string") throw new Error(`${match[0]} in ${name} is not a method`);
    tags.add(tag);
  }
  return tags;
}
const payloadRules = [
  ...new Set([
    ...namedTags(AUTH_FILE, "requiredScopesForRpcCall"),
    ...namedTags(CLIENT_FILE, "clientRpcRequiredScopes"),
  ]),
].sort();

// Settings keys that need `providers:manage`: ask the T3 function key by key.
const patchKeys = Object.keys(settings.ServerSettingsPatch.fields).sort();
const providerKeys = patchKeys.filter((key) =>
  settings.requiredScopesForServerSettingsPatch({ [key]: {} }).includes("providers:manage"),
);
if (providerKeys.length === 0) throw new Error("no settings key needs providers:manage");

// Scope rules inside handlers, outside the two maps.
const inHandler = [
  ...NodeFS.readFileSync(inMonorepo(AUTH_FILE), "utf8").matchAll(
    /export const (requiredScopeFor\w+)/g,
  ),
].map((m) => m[1]);

const scopesRs = rustfmt(
  [
    ...HEADER,
    `// Sources: ${AUTH_FILE} (RPC_REQUIRED_SCOPES, requiredScopesForRpcCall),`,
    `// ${CLIENT_FILE} (clientRpcRequiredScopes), packages/contracts/src/settings.ts`,
    "// (requiredScopesForServerSettingsPatch).",
    "",
    "/// Every RPC method with the scope it needs, sorted by tag.",
    "pub(super) const SCOPES: &[(&str, &str)] = &[",
    ...scopes.map(([tag, scope]) => `(${str(tag)}, ${str(scope)}),`),
    "];",
    "",
    "/// The methods whose scope the T3 server computes from the payload. `scopes.rs` keeps",
    "/// these rules by hand; its test fails when they differ from this list.",
    "pub(super) const PAYLOAD_RULES: &[&str] = &[",
    ...payloadRules.map((tag) => `${str(tag)},`),
    "];",
    "",
    "/// Settings keys whose change needs `providers:manage`; any other key needs `settings:write`.",
    "pub(super) const PROVIDER_SETTINGS: &[&str] = &[",
    ...providerKeys.map((key) => `${str(key)},`),
    "];",
    "",
    "/// Scope rules the T3 server applies inside a handler, outside the method table. A served",
    "/// method that has one must apply it by hand; `scopes.rs` tests that none is served.",
    "#[cfg(test)]",
    "pub(super) const IN_HANDLER_RULES: &[&str] = &[",
    ...inHandler.map((name) => `${str(name)},`),
    "];",
    "",
  ].join("\n"),
);

// ---- Write or check ----------------------------------------------------------------------

const outputs = {
  "crates/conn-server/src/scopes/generated.rs": scopesRs,
};

let stale = false;
for (const [rel, content] of Object.entries(outputs)) {
  const file = NodePath.join(repoRoot, rel);
  if (check) {
    const current = NodeFS.existsSync(file) ? NodeFS.readFileSync(file, "utf8") : undefined;
    if (current !== content) {
      console.error(`${rel} is stale; run tools/gen-upstream.mjs without --check`);
      stale = true;
    }
  } else {
    NodeFS.mkdirSync(NodePath.dirname(file), { recursive: true });
    NodeFS.writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
console.log(
  `scopes: ${scopes.length} methods, ${payloadRules.length} payload rules, ${providerKeys.length} provider settings keys`,
);
for (const name of inHandler) {
  console.log(`note: ${AUTH_FILE} checks a scope inside a handler: ${name}`);
}
if (stale) process.exit(1);
if (check) console.log("upstream tables are current");
