    "    /// `JSON.stringify` of the trimmed project name.",
    "    Project,",
    "    /// `JSON.stringify` of the previous title.",
    "    Previous,",
    "    /// The (limited) message or thread contents.",
    "    Message,",
    "}",
    "",
