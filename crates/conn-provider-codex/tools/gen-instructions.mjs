#!/usr/bin/env node
// Writes src/instructions.rs: the text the T3 server puts in a Codex turn's
// `additionalContext` when the thread has T3's MCP server (`buildCodexAdditionalContext` in
// apps/server/src/provider/CodexDeveloperInstructions.ts), taken from the monorepo at
// CONN_MONOREPO so it stays byte for byte equal. Also writes testdata/instructions.json:
// what the TS function returns for a few runtimes, which `instructions::tests` compares with
// the Rust build of the same values.
//
//   CONN_MONOREPO=/path/to/conn node crates/conn-provider-codex/tools/gen-instructions.mjs [--check]
//
// `--check` exits 1 when either file is out of date.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { inMonorepo } from "../../../tools/monorepo.mjs";

const HERE = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const CRATE = NodePath.dirname(HERE);
const check = process.argv.includes("--check");
const load = (relative) => import(NodeURL.pathToFileURL(inMonorepo(relative)).href);

const orchestration = await load("packages/provider-core/src/server/orchestrationInstructions.ts");
const runtime = await load("packages/provider-core/src/server/runtimeInstructions.ts");
const codex = await load("apps/server/src/provider/CodexDeveloperInstructions.ts");

/** A Rust raw string literal that holds `text` unchanged. */
const raw = (text) => {
  let hashes = "#";
  while (text.includes(`"${hashes}`)) hashes += "#";
  return `r${hashes}"${text}"${hashes}`;
};

const sections = orchestration.T3_CODE_ORCHESTRATION_SECTIONS;
const rust = `// @generated by tools/gen-instructions.mjs from the Conn monorepo. Do not edit.
// Regenerate: CONN_MONOREPO=<conn checkout> node crates/conn-provider-codex/tools/gen-instructions.mjs

/// \`T3_CODE_ORCHESTRATION_SECTIONS\` (\`orchestrationInstructions.ts\`).
pub const ORCHESTRATION_SECTIONS: &[&str] = &[
${sections.map((s) => `    ${raw(s)},`).join("\n")}
];

/// \`T3_CODE_BROWSER_TOOL_INSTRUCTIONS\`.
pub const BROWSER_TOOLS: &str = ${raw(orchestration.T3_CODE_BROWSER_TOOL_INSTRUCTIONS)};

/// \`T3_CODE_DEVICE_TOOL_INSTRUCTIONS\`.
pub const DEVICE_TOOLS: &str = ${raw(orchestration.T3_CODE_DEVICE_TOOL_INSTRUCTIONS)};

/// \`PULL_REQUEST_LINKING_INSTRUCTIONS\` (\`runtimeInstructions.ts\`).
pub const PULL_REQUEST_LINKING: &str = ${raw(runtime.PULL_REQUEST_LINKING_INSTRUCTIONS)};
`;

// Cases for the Rust build of `buildRuntimeInstructions` and the entry keys.
const cases = [
  { runtime: { model: "gpt-6-luna" }, tools: true },
  { runtime: { model: "gpt-6-astra", reasoningEffort: "medium" }, tools: { browser: false, device: true } },
  { runtime: { model: "  gpt  6\n", reasoningEffort: "high" }, tools: { browser: true, device: true } },
  { runtime: { model: "auto" }, tools: { browser: false, device: false } },
  { runtime: { model: "default", reasoningEffort: "" }, tools: false },
];
const samples = cases.map((c) => ({ ...c, context: codex.buildCodexAdditionalContext(c.runtime, c.tools) }));
const json = `${JSON.stringify(samples, null, 1)}\n`;

const outputs = [
  [NodePath.join(CRATE, "src/instructions.rs"), rust],
  [NodePath.join(CRATE, "testdata/instructions.json"), json],
];
let stale = 0;
for (const [file, content] of outputs) {
  const current = NodeFS.existsSync(file) ? NodeFS.readFileSync(file, "utf8") : undefined;
  if (current === content) continue;
  if (check) {
    console.error(`${NodePath.relative(CRATE, file)} is out of date: run tools/gen-instructions.mjs`);
    stale += 1;
  } else {
    NodeFS.writeFileSync(file, content);
    console.log(`wrote ${NodePath.relative(CRATE, file)}`);
  }
}
if (check && stale === 0) console.log("instructions current");
process.exit(stale === 0 ? 0 : 1);
