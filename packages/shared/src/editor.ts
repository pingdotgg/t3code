type Editor = (typeof EDITORS)[number];

const installNames: Partial<Record<Editor["id"], ReadonlyArray<string>>> = {
  vscode: ["Visual Studio Code"],
  "vscode-insiders": ["Visual Studio Code - Insiders"],
  // `Antigravity.app` is the separate Hub, not the IDE.
  antigravity: ["Antigravity IDE"],
  idea: ["IntelliJ IDEA", "IntelliJ IDEA CE", "IntelliJ IDEA Ultimate"],
  pycharm: ["PyCharm", "PyCharm CE"],
  rider: ["Rider", "JetBrains Rider"],
};

// Prefix-only matches could select Insiders when resolving stable VS Code.
const isVersionedBundle = (entry: string, name: string) => {
  if (!entry.startsWith(`${name} `) || !entry.endsWith(".app")) return false;
  return /^\d[\d.]*$/.test(entry.slice(name.length + 1, -".app".length));
};

const scriptWords = (line: string) =>
  [...line.replace(/^\s*\(/, "").matchAll(/"([^"]*)"|'([^']*)'|(\S+)/g)].map((match) => ({
    text: match[1] ?? match[2] ?? match[3] ?? "",
    quoted: match[3] === undefined,
  }));

/** Only the launched program shows whether the IDE is still installed; other paths on the line,
 * such as `> /dev/null` or `JAVA_HOME="/opt/jdk"`, do not. */
const launchedProgram = (line: string) => {
  const words = scriptWords(line);
  const launcher = words.shift();
  if (!launcher) return undefined;
  const name = launcher.text.toLowerCase();
  if (name === "start") {
    // CMD's `start` takes `/switch` options, some with an operand, and one quoted window title.
    let title = false;
    while (words[0]) {
      const word = words[0];
      if (!word.quoted && word.text.startsWith("/")) {
        words.shift();
        if (/^\/(d|node|affinity)$/i.test(word.text)) words.shift();
      } else if (word.quoted && !title) {
        title = true;
        words.shift();
      } else break;
    }
    return words[0]?.text;
  }
  if (name !== "exec" && name !== "open") return launcher.text;
  return words.find((word) => word.quoted || !word.text.startsWith("-"))?.text;
};

// The launch scripts Toolbox 3.9 writes, split around the IDE path. Toolbox passes arguments through
// its own variables (`$wait`, `%intellij_args%`), so these are matched whole instead of parsed.
const toolboxTemplates = [
  [
    "#!/bin/bash",
    /^#Generated by JetBrains Toolbox [\d.]+ at [\dT:.-]+$/,
    `\ndeclare -a intellij_args=()\ndeclare -- wait=""\n\nfor o in "$@"; do\n  if [[ "$o" = "--wait" || "$o" = "-w" ]]; then\n    wait="-W"\n    o="--wait"\n  fi\n  if [[ "$o" =~ " " ]]; then\n    intellij_args+=("\\"$o\\"")\n  else\n    intellij_args+=("$o")\n  fi\ndone\n\nopen -na "`,
    `" $wait --args "\${intellij_args[@]}"`,
    // Characters Bash expands or drops inside double quotes, and bytes the text decoder replaced.
    /["$`\\\x00-\x1f\x7f\ufffd]/,
  ],
  [
    "@echo off",
    /^rem Generated by JetBrains Toolbox [\d.]+ at [\dT:.-]+$/,
    `\nset waitarg=\nset intellij_args=\n\n:next\nset "passwait="\nif "%~1"=="--wait" set passwait=1\nif "%~1"=="-w" set passwait=1\nif defined passwait (set waitarg=/wait)\nif not "%~1"=="" (\n  if defined passwait (set "intellij_args=%intellij_args%--wait ") else (set "intellij_args=%intellij_args%%1 ")\n  shift\n  goto next\n)\n\nstart "" %waitarg% "`,
    `" %intellij_args%`,
    // Characters CMD expands inside double quotes, and anything past ASCII, which CMD reads in the
    // console code page.
    /["%!]|[^\x20-\x7e]/,
  ],
] as const;

/** The IDE path of a script exactly as Toolbox wrote it; any edit gives `undefined`. */
const toolboxTarget = (text: string) => {
  const [first, header, ...rest] = text.replace(/\r\n/g, "\n").trimEnd().split("\n");
  const body = rest.join("\n");
  for (const [shebang, headerLine, before, after, expanded] of toolboxTemplates) {
    if (first !== shebang || !headerLine.test(header ?? "")) continue;
    if (!body.startsWith(before) || !body.endsWith(after)) continue;
    const target = body.slice(before.length, body.length - after.length);
    if (!expanded.test(target)) return target;
  }
  return undefined;
};

// OpenZFS's event daemon is also named zed; it rejects `--version` instead of starting.
const isZedEditor = Effect.fn("editor.isZedEditor")(
  function* (command: string) {
    const spawner = yield* ChildProcessSpawner.ChildProcessSpawner;
    const handle = yield* spawner.spawn(
      ChildProcess.make(command, ["--version"], {
        stdin: "ignore",
        stderr: "ignore",
        forceKillAfter: "1 second",
      }),
    );
    const [stdout, exitCode] = yield* Effect.all(
      [handle.stdout.pipe(Stream.decodeText(), Stream.runHead), handle.exitCode],
      { concurrency: "unbounded" },
    );
    return exitCode === 0 && Option.getOrElse(stdout, () => "").startsWith("Zed");
  },
  Effect.scoped,
  Effect.timeout("2 seconds"),
  Effect.catchCause(() => Effect.succeed(false)),
);

export const resolveEditorCommand = Effect.fn("editor.resolveEditorCommand")(function* (
  editor: Editor,
  env: NodeJS.ProcessEnv,
) {
  if (editor.commands === null) return Option.none();
  const baseArgs = "baseArgs" in editor ? editor.baseArgs : [];
  const platform = yield* HostProcess.Platform;
  // Prefer Zed's macOS bundle because OpenZFS also installs a zed executable.
  const preferBundle = platform === "darwin" && editor.id === "zed";
  const preferZeditor = platform === "linux" && editor.id === "zed";
  const path = yield* Path.Path;
  const fs = yield* FileSystem.FileSystem;
  const home = env.HOME;
  const names = installNames[editor.id] ?? [editor.label];
  const command = editor.commands[0];
  const jetbrains = editor.launchStyle === "line-column";
  const dataHome = env.XDG_DATA_HOME || (home ? path.join(home, ".local/share") : undefined);
  const toolboxRoot =
    platform === "darwin"
      ? home && path.join(home, "Library/Application Support")
      : platform === "win32"
        ? env.LOCALAPPDATA
        : platform === "linux"
          ? dataHome
          : undefined;
  const toolboxDir =
    jetbrains && toolboxRoot ? path.join(toolboxRoot, "JetBrains/Toolbox/scripts") : undefined;
  const scriptSuffix = platform === "win32" ? ".cmd" : "";
  // A Toolbox script launches its IDE by absolute path or a HOME-based path, so a script left
  // behind by a removed IDE names only missing paths. The script is read, never run.
  const launchTargetStatus = Effect.fn("editor.launchTargetStatus")(function* (
    script: string,
    onlyToolboxScript = false,
  ) {
    const text = yield* fs.readFileString(script).pipe(Effect.orElseSucceed(() => ""));
    const lines = text.split(/\r?\n/);
    const expand = (word: string) =>
      home ? word.replace(/^(?:\$HOME|\$\{HOME\}|~)(?=\/)/, () => home) : word;
    const exists = (target: string) => fs.exists(target).pipe(Effect.orElseSucceed(() => false));
    const target = toolboxTarget(text);
    if (target !== undefined && path.isAbsolute(target)) {
      return (yield* exists(target)) ? "found" : "missing";
    }
    if (onlyToolboxScript) return "unknown";
    const programs = lines.flatMap((line) => launchedProgram(line) ?? []).map(expand);
    const targets = programs.filter(
      (program) => path.isAbsolute(program) && path.basename(program) !== "env",
    );
    for (const target of targets) {
      if (yield* exists(target)) return "found";
    }
    // A variable other than HOME or the forwarded arguments (`$IDE_HOME`, `%IDE%`) or an escaped
    // space (`IntelliJ\ IDEA.app`) can hide an installed IDE from this parser.
    const ambiguous = /\$|%[\w~]|\\ /.test(text.replace(/\$(?:\{HOME\}|HOME\b|@|\*)|%\*/g, ""));
    if (targets.length === 0 || ambiguous) return "unknown";
    // Any other existing path, as in `env "/opt/idea/bin/idea"`, may be the IDE behind a launcher
    // this parser does not know.
    for (const { text: word } of lines.flatMap(scriptWords)) {
      const target = expand(word);
      if (path.isAbsolute(target) && (yield* exists(target))) return "unknown";
    }
    return "missing";
  });
  if (!preferBundle && !preferZeditor) {
    for (const name of editor.commands) {
      const found = yield* resolveCommandPath(name, { env });
      if (found === null) continue;
      // Toolbox puts its scripts directory on PATH, where a script left by a removed IDE would win.
      const staleToolboxScript =
        toolboxDir !== undefined &&
        path.relative(toolboxDir, path.dirname(found)) === "" &&
        (yield* launchTargetStatus(found, true)) === "missing";
      if (!staleToolboxScript) return Option.some({ command: name, baseArgs });
    }
  }

  // Toolbox names a launch script `idea1`, `idea2`, ... when another installed version already
  // has `idea`. The canonical script stays unless its IDE is positively gone; a numbered one needs
  // a target that still exists.
  const toolboxScripts = Effect.fn("editor.toolboxScripts")(function* (dir: string) {
    const canonical = path.join(dir, `${command}${scriptSuffix}`);
    const entries = yield* fs.readDirectory(dir).pipe(Effect.orElseSucceed(() => []));
    const numbered = entries
      .filter(
        (entry) =>
          entry.startsWith(command) &&
          entry.endsWith(scriptSuffix) &&
          /^\d+$/.test(entry.slice(command.length, entry.length - scriptSuffix.length)),
      )
      .sort((a, b) => a.length - b.length || a.localeCompare(b))
      .map((entry) => path.join(dir, entry));
    return [
      ...((yield* launchTargetStatus(canonical)) === "missing" ? [] : [canonical]),
      ...(yield* Effect.filter(numbered, (script) =>
        launchTargetStatus(script).pipe(Effect.map((status) => status === "found")),
      )),
    ];
  });
  const candidates: string[] = [];

  if (platform === "darwin") {
    const roots = [...(home ? [path.join(home, "Applications")] : []), "/Applications"];
    for (const root of roots) {
      // JetBrains Toolbox appends versions to bundle names; accept exact and versioned names.
      const entries = yield* fs.readDirectory(root).pipe(Effect.orElseSucceed(() => []));
      const bundles = new Set(names.map((name) => `${name}.app`));
      for (const entry of entries) {
        if (names.some((name) => entry === `${name}.app` || isVersionedBundle(entry, name))) {
          bundles.add(entry);
        }
      }
      for (const bundle of bundles) {
        const contents = path.join(root, bundle, "Contents");
        candidates.push(
          ...(jetbrains || editor.id === "zed"
            ? [path.join(contents, "MacOS", editor.id === "zed" ? "cli" : command)]
            : [
                path.join(contents, "Resources/app/bin", command),
                path.join(contents, "Resources/app/bin/code"),
              ]),
        );
      }
    }
    if (toolboxDir) candidates.push(...(yield* toolboxScripts(toolboxDir)));
  } else if (platform === "win32") {
    const roots = [
      ...(env.LOCALAPPDATA ? [path.join(env.LOCALAPPDATA, "Programs")] : []),
      ...[env.ProgramFiles, env["ProgramFiles(x86)"], env.ProgramW6432].filter(
        (root): root is string => !!root,
      ),
    ];
    if (jetbrains) {
      if (toolboxDir) candidates.push(...(yield* toolboxScripts(toolboxDir)));
      for (const directory of roots.flatMap((root) => [root, path.join(root, "JetBrains")])) {
        const entries = yield* fs.readDirectory(directory).pipe(Effect.orElseSucceed(() => []));
        for (const entry of entries) {
          if (names.some((name) => entry === name || entry.startsWith(`${name} `))) {
            candidates.push(path.join(directory, entry, "bin", `${command}64.exe`));
            candidates.push(path.join(directory, entry, "bin", `${command}.exe`));
          }
        }
      }
    } else {
      const name =
        editor.id === "vscode"
          ? "Microsoft VS Code"
          : editor.id === "vscode-insiders"
            ? "Microsoft VS Code Insiders"
            : editor.label;
      for (const root of roots) {
        candidates.push(
          path.join(root, name, "resources/app/bin", `${command}.cmd`),
          path.join(root, name, "resources/app/bin/code.cmd"),
          path.join(root, name, "bin", `${command}.cmd`),
          path.join(root, name, "bin/code.cmd"),
        );
        if (editor.id === "zed") {
          candidates.push(
            path.join(root, name, "bin", "zed.exe"),
            path.join(root, name, "zed.exe"),
          );
        }
      }
    }
  } else if (platform === "linux") {
    const dirs = [
      ...(home ? [path.join(home, ".local/bin")] : []),
      "/usr/local/bin",
      "/usr/bin",
      "/snap/bin",
    ];
    if (preferZeditor) {
      // Linux packages use zeditor because OpenZFS owns the zed command.
      for (const name of ["zeditor", "zed"]) {
        candidates.push(name, ...dirs.map((dir) => path.join(dir, name)));
      }
    } else {
      for (const dir of dirs) {
        for (const name of editor.commands) candidates.push(path.join(dir, name));
      }
    }
    if (toolboxDir) candidates.push(...(yield* toolboxScripts(toolboxDir)));
  }

  if (preferBundle) candidates.push(...editor.commands);
  const rejected = new Set<string>();
  for (const candidate of candidates) {
    const resolved = yield* resolveCommandPath(candidate, { env });
    if (resolved === null || rejected.has(resolved)) continue;
    if (preferZeditor && path.basename(candidate) === "zed" && !(yield* isZedEditor(resolved))) {
      rejected.add(resolved);
      continue;
    }
    return Option.some({
      command: candidate,
      baseArgs:
        editor.id === "kiro" && (platform === "darwin" || platform === "win32") ? [] : baseArgs,
    });
  }
  return Option.none();
});
